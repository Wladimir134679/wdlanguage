package ru.wds.wdl.tools.service;

/**
 * Чем красить кусок текста.
 * <p>
 * Список нарочно короткий и говорит о <b>смысле</b>, а не о цвете: цвет выбирает
 * тема редактора, и называть здесь «синий» значило бы сломать любую тему, кроме той,
 * в которой это писали.
 * <p>
 * Виды имён совпадают с {@link ru.wds.wdl.tools.analysis.SymbolKind} не полностью:
 * подсветке всё равно, остаток это или обычный параметр, а различать переменную
 * и константу ей нужно — константа не меняется, и это видно с первого взгляда.
 */
public enum TokenStyle {

    /** {@code def}, {@code if}, {@code class}, {@code true} — всё, что слово языка. */
    KEYWORD,

    /** {@code //} и {@code /* *&#47;} целиком. */
    COMMENT,

    STRING,

    NUMBER,

    /** {@code +}, {@code ==}, {@code =>}. Скобки и запятые сюда не попадают. */
    OPERATOR,

    VARIABLE,

    CONSTANT,

    PARAMETER,

    FUNCTION,

    /** Метод, фабрика, требование трейта — всё, что зовётся на значении. */
    METHOD,

    PROPERTY,

    CLASS,

    TRAIT,

    /** Псевдоним модуля из {@code import}. */
    MODULE,

    /**
     * Символ, который в языке не значит ничего.
     * <p>
     * Отдельным видом, а не пропуском: во встроенном редакторе мусор подчёркивают
     * прямо в потоке токенов, до всякой диагностики.
     */
    BAD
}
