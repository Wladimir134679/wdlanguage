package ru.wds.wdl.tools.catalog;

/**
 * Откуда имя взялось: язык, библиотека, модуль или приложение.
 * <p>
 * Нужно двоим и обоим по делу. Дополнению — чтобы сортировать: своё имя из файла
 * идёт первым, встроенное вторым, чужое дальше. Наведению — чтобы объяснить, почему
 * имя вообще существует: «{@code println} — встроенная функция» и «{@code total} —
 * функция приложения» отвечают на разные вопросы, хотя выглядят одинаково.
 * <p>
 * Различать прелюдию и встроенные функции отдельно смысла нет: и то и другое кладёт
 * в область сам движок до первой строки скрипта, и для человека это одно и то же —
 * «оно есть всегда».
 */
public enum Origin {

    /** Объявлено в самом файле: это ответ анализа, а не каталога. */
    FILE("файл"),

    /** Встроенные функции, дескрипторы типов и классы прелюдии: есть в любом запуске. */
    BUILTIN("встроенное"),

    /** Имя библиотеки, положенное в корневую область: {@code sqrt}, {@code File}. */
    LIBRARY("библиотека"),

    /** Имя внутри модуля: то, что видно после {@code import sys.io as io}. */
    MODULE("модуль"),

    /** Имя, заведённое встраивающим приложением. */
    HOST("приложение");

    private final String title;

    Origin(String title) {
        this.title = title;
    }

    /** Как назвать источник человеку — в подсказке. */
    public String title() {
        return title;
    }
}
