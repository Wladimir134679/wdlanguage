package ru.wds.wdl.tools.analysis;

/**
 * Вид области видимости.
 * <p>
 * Список не выдуман, а сверен с {@code Interpreter}: каждому виду соответствует место,
 * где выполнение заводит вложенное окружение ({@code context.nested()}). Тело {@code if}
 * без фигурных скобок своей области не создаёт — там нет блока, — и здесь его тоже нет.
 * <p>
 * {@link #FUNCTION_BODY} стоит особняком: это единственная граница, которая меняет
 * правило видимости. Внутри тела видно всё, что объявлено снаружи, включая объявленное
 * ниже по файлу, — потому что тело выполняется позже. Остальные виды такой силы
 * не имеют.
 */
public enum ScopeKind {

    /** Верхний уровень файла. */
    FILE("файл"),

    /** Тело функции вместе с её параметрами. */
    FUNCTION_BODY("тело функции"),

    /** Блок в фигурных скобках. */
    BLOCK("блок"),

    /** Заголовок и тело {@code for (i = 0; ...)}: переменная счётчика живёт здесь. */
    LOOP("цикл"),

    /** Шаг перебора {@code for (item in cart)}: имена прохода живут здесь. */
    ITERATION("проход цикла"),

    /** {@code use (file = ...)}: захваченные ресурсы. */
    USE("use"),

    /** Обработчик {@code catch (e)}: имя ошибки живёт только здесь. */
    CATCH("catch"),

    /** Тело класса: поля заголовка, методы, свойства, фабрики. */
    CLASS_BODY("тело класса"),

    /** Тело трейта: поля, методы, требования, свойства. */
    TRAIT_BODY("тело трейта"),

    /** Тело расширения {@code extend}: методы и свойства чужого типа. */
    EXTENSION_BODY("тело расширения"),

    /** Тело аксессора свойства со скрытым полем: здесь существует {@code field}. */
    ACCESSOR("аксессор");

    private final String title;

    ScopeKind(String title) {
        this.title = title;
    }

    public String title() {
        return title;
    }

    /** Граница вызова: снаружи неё видно всё, а не только объявленное выше. */
    public boolean isCallBoundary() {
        return this == FUNCTION_BODY || this == ACCESSOR;
    }
}
