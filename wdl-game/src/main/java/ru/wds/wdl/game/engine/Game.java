package ru.wds.wdl.game.engine;

/**
 * Игра глазами движка: пять точек, в которых игра получает управление.
 * <p>
 * Движок не знает ни про wdl, ни про скрипты — он знает этот интерфейс. Что стоит
 * за ним, дело вызывающего: {@code ru.wds.wdl.game.script} подставляет сюда функции
 * скрипта, а тест — обычную Java-лямбду. Ровно эта граница и делает модуль тем,
 * ради чего он написан: движок остаётся движком, а встраивание языка — отдельным
 * слоем поверх него, который можно снять и заменить.
 *
 * <h2>Порядок кадра</h2>
 * <ol>
 *   <li>{@link #start()} — один раз, до первого кадра;</li>
 *   <li>{@link #key} — на каждое нажатие и отпускание, накопленные с прошлого кадра;</li>
 *   <li>спрайты сдвигаются на свою скорость;</li>
 *   <li>{@link #update(double)} — игра видит уже сдвинутый мир и правит его;</li>
 *   <li>{@link #draw(Painter)} — поверх нарисованных движком спрайтов;</li>
 *   <li>{@link #stop()} — один раз, когда цикл закончился сам.</li>
 * </ol>
 * Все методы зовутся из <b>одного</b> потока — того, который позвал
 * {@link Engine#run}. Поэтому игре не нужно ни замков, ни очередей.
 */
public interface Game {

    /** До первого кадра: расставить объекты, подать мяч. */
    default void start() {
    }

    /**
     * Кадр игры.
     *
     * @param dt сколько секунд прошло с прошлого кадра — не больше
     *           {@link GameLoop#MAX_STEP}
     */
    default void update(double dt) {
    }

    /** Своя графика поверх спрайтов: счёт, сетка, подсказки. */
    default void draw(Painter canvas) {
    }

    /**
     * Нажатие или отпускание клавиши.
     *
     * @param key  имя клавиши: {@code "left"}, {@code "space"}, {@code "w"}
     * @param down {@code true} — нажали, {@code false} — отпустили
     */
    default void key(String key, boolean down) {
    }

    /** Цикл кончился штатно: окно закрыли или игра попросила остановиться. */
    default void stop() {
    }
}
