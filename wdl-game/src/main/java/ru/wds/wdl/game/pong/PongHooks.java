package ru.wds.wdl.game.pong;

import ru.wds.wdl.game.engine.Painter;
import ru.wds.wdl.game.engine.Sprite;

/**
 * Решения, отданные скрипту: пять вопросов, на которые игра не отвечает сама.
 * <p>
 * Это вся граница между пинг-понгом и wdl — и она нарочно описана обычным
 * Java-интерфейсом. {@link Pong} про язык не знает ничего: он зовёт эти пять
 * методов, а кто за ними стоит — встроенные скрипты, лямбда теста или будущая
 * настройка сложности, — его не касается. Ровно та же граница, что у движка
 * с {@link ru.wds.wdl.game.engine.Game}, только на этаж выше.
 *
 * <h2>Почему именно эти пять</h2>
 * Разделение проходит по линии «физика или правило». Как летит мяч, кто кого
 * коснулся, когда он пересёк край поля — физика, она в Java: считать её скриптом
 * значило бы платить вызовом за каждое сравнение. С какой скоростью подавать,
 * куда отскочить от ракетки, что делает соперник, когда партия закончена и что
 * написано на экране — правила, и меняются они чаще всего. Меняются — значит
 * должны меняться без пересборки.
 *
 * <h2>Хук возвращает решение, а не выполняет его</h2>
 * Где это возможно — {@link #rival} возвращает скорость, {@link #point} отвечает
 * «партия сыграна?» — скрипт остаётся чистой функцией, и его можно позвать в тесте,
 * не заводя ни поля, ни мяча. Там, где решение сложнее числа ({@link #serve},
 * {@link #bounce}), скрипт правит скорость мяча прямо, потому что придумывать ради
 * этого тип «намерение» дороже, чем отдать спрайт.
 */
public interface PongHooks {

    /**
     * Подача: скрипт задаёт мячу скорость.
     * <p>
     * Мяч в этот момент стоит у ракетки подающего, {@code match.serving()} говорит,
     * у чьей. Направление — забота скрипта: разогнать мяч в свою сторону значит
     * подать самому себе.
     */
    void serve(Match match, Sprite ball);

    /**
     * Отскок от ракетки: мяч уже выставлен вплотную к её краю, знак скорости ещё
     * прежний. Скрипт решает, куда мяч пойдёт дальше и насколько ускорится.
     */
    void bounce(Match match, Sprite ball, Sprite paddle);

    /**
     * Скорость ракетки соперника по вертикали на этот кадр, в пикселях в секунду.
     * <p>
     * Весь ИИ игры — здесь. Ракетку двигает движок, в поле её держит {@link Pong};
     * скрипту остаётся ровно одно решение, и оно выражается одним числом.
     */
    double rival(Match match, Sprite ball, Sprite paddle);

    /**
     * Очко засчитано названной стороне — счёт уже изменён.
     *
     * @return {@code true}, если партия на этом кончается
     */
    boolean point(Match match, Match.Side side);

    /**
     * Надписи поверх кадра: счёт, сетка, подсказки.
     * <p>
     * Спрайты движок к этому моменту уже нарисовал, холст живёт до конца кадра.
     */
    void hud(Match match, Painter canvas);
}
