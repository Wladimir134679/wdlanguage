/**
 * WDGame — маленький игровой движок и площадка для проверки встраивания.
 * <p>
 * Модуль устроен как <b>приложение-хозяин</b>, а не как часть языка: он собирает
 * {@code WdlEngine}, кладёт рядом со стандартной библиотекой свой модуль
 * {@code game} ({@link ru.wds.wdl.game.Games}) и отдаёт управление скрипту —
 * ровно так, как поступила бы чужая игра, решившая, что моды к ней пишут на wdl.
 * <p>
 * Игра выбрана не случайно: это самое требовательное приложение из тех, что зовут
 * скрипт, — шестьдесят раз в секунду, из своего цикла, с ожиданием ответа
 * до следующего кадра. Всё, что в таком режиме окажется неудобным или дорогим,
 * должно найтись здесь.
 *
 * <h2>Две половины и граница между ними</h2>
 * {@code ru.wds.wdl.game.engine} — сам движок: сцена, спрайты, ввод, окно, цикл
 * кадров и холст. Он <b>не знает про wdl ничего</b> и разговаривает с игрой через
 * интерфейс {@link ru.wds.wdl.game.engine.Game} из пяти методов.
 * {@code ru.wds.wdl.game.script} — слой встраивания: те же пять методов, за которыми
 * стоят функции скрипта. Снять этот слой, не тронув движка, можно в любой момент;
 * ради такой проверки всё и написано.
 * <p>
 * Описание для автора игры — в {@code docs/game.md}, пример — в
 * {@code examples/game/pong.wdl}.
 */
