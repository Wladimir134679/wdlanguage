package ru.wds.wdl.stdlib.streams;

import ru.wds.wdl.value.Value;

/**
 * Звено конвейера: следующий элемент или {@code null}, когда элементы кончились.
 * <p>
 * Источник и стадия — это одно и то же понятие, и разница между ними только в том,
 * откуда звено берёт элементы: источник — из файла, массива, канала, счётчика; стадия —
 * из предыдущего звена. Поэтому интерфейс один: {@code map} поверх {@code filter}
 * поверх {@code lines} собирается сам собой, а терминальная операция знает ровно одно
 * слово — {@link #next()}.
 *
 * <h2>Тянут, а не проталкивают</h2>
 * Модель — pull: звено само просит у предыдущего, а не предыдущее толкает в него.
 * Java выбрала push ({@code Sink.accept} плюс флаг отмены) и получила скорость ценой
 * составимости: {@code zip} двух потоков в push-модели не выражается вовсе — оттого
 * его в Java до сих пор и нет. Здесь же {@code zip}, {@code chunked} и
 * {@code windowed} — это просто звенья, которые зовут {@code next()} столько раз,
 * сколько им надо.
 * <p>
 * Цена pull — виртуальный вызов на элемент на каждую стадию. На фоне вызова функции
 * скрипта (кадр, точка проверки лимитов, запись профиля) это шум: push выигрывает там,
 * где стадия дешевле вызова, а здесь стадия <b>и есть</b> вызов.
 *
 * <h2>Почему {@code null} — это конец</h2>
 * Элемент потока — всегда {@link Value}, в худшем случае {@code NullValue.NULL}:
 * Java-{@code null} в значениях языка не ходит нигде. Поэтому {@code null} свободен
 * под признак исчерпания, и коробка вокруг каждого элемента ({@code Optional},
 * {@code boolean hasNext}) не нужна — а нужна была бы на каждом элементе каждой стадии.
 *
 * <h2>Закрытие идёт вверх</h2>
 * {@link #close()} каждой стадии закрывает предыдущую, и так до источника: иначе
 * {@code lines(path).filter(p).first()} оставил бы открытый файл. Закрывает
 * терминальная операция — из {@code finally}, чем бы обход ни кончился.
 * {@code close()} объявлен без {@code throws}, потому что закрывать конвейер приходится
 * на пути наружу из ошибки, и обрастать там вторым обработчиком незачем.
 */
@FunctionalInterface
interface Source extends AutoCloseable {

    /** Следующий элемент или {@code null}, если их больше нет. */
    Value next();

    /** Отпускает то, что держит звено, и то, что держат звенья выше. Идемпотентно. */
    @Override
    default void close() {
    }
}
