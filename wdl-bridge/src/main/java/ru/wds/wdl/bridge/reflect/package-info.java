/**
 * Мост в Java: чужой класс и готовый объект — как класс и объект языка.
 * <p>
 * Отвечает на два разных вопроса, у которых один ответ. Первый: приложение хочет
 * отдать скрипту <b>тип</b> — {@code java.time.LocalDate}, свой {@code Order}, —
 * чтобы скрипт создавал экземпляры и звал методы. Второй: библиотека вернула
 * <b>готовый объект</b>, которого приложение не создавало и оборачивать вручную
 * не собирается, — соединение, результат запроса, момент времени.
 *
 * <h2>Чем это отличается от {@link ru.wds.wdl.bridge.NativeClass}</h2>
 * Граница простая: <b>построитель — для своих классов, мост — для чужих.</b>
 * Своему классу построитель даёт точные имена, проверку компилятором и никакой
 * рефлексии — и остаётся правильным выбором. Чужой класс построителем оборачивать
 * значит писать по методу на каждый метод, и после каждого обновления библиотеки
 * писать снова.
 * <p>
 * Есть и третий случай, который до {@link ru.wds.wdl.bridge.reflect.FromJava}
 * не описывался никак: <b>своя обёртка над чужим типом</b>. Класс свой — свой
 * конструктор, своё состояние, свои обработчики, — но половина его методов дословно
 * повторяет тип, лежащий у него в {@code state()}. Такие члены берутся у этого типа
 * и объявляются <b>тем же словарём построителя</b>, что и написанные лямбдами.
 *
 * <h2>Что видит скрипт</h2>
 * Обычный класс и обычный объект. Ни нового типа значения, ни нового синтаксиса:
 * {@code typeof} даёт {@code object}, {@code is} отвечает, {@code println} печатает,
 * члены ищутся тем же путём, что у всех. Держится это на том, что классов
 * в языке ровно два вида: написанный на wdl и {@link ru.wds.wdl.bridge.NativeClass}
 * от приложения. Открытый мостом Java-тип — не третий вид, а тот же
 * {@code NativeClass}, у которого члены пришли не из лямбд, а из рефлексии
 * ({@link ru.wds.wdl.bridge.reflect.FromJava}).
 *
 * <h2>По умолчанию закрыт</h2>
 * Мост, открытый целиком, — это дыра в две строки: {@code obj.getClass()
 * .getClassLoader()}. Поэтому {@code getClass} не экспортируется никогда, опасные
 * типы стоят в чёрном списке, а неизвестный Java-объект оборачивается только тогда,
 * когда приложение это разрешило. См. {@link ru.wds.wdl.bridge.reflect.JavaPolicy}.
 */
