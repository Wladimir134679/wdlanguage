package ru.wds.wdl.bridge;

/**
 * Откуда классу взять члены, кроме как из написанных руками лямбд.
 * <p>
 * Появился для одного случая, который до него не описывался никак:
 * <b>своя обёртка над чужим типом</b>. Класс {@code Button} — свой: у него свой
 * конструктор, своё состояние и обработчик {@code onClick}, которого у {@code JButton}
 * нет и быть не может. Но {@code setText}/{@code getText}/{@code setEnabled} у него
 * ровно те же, что у {@code JButton}, и переписывать их лямбдами значило делать
 * чужую работу второй раз — а потом делать её заново после обновления библиотеки.
 * <p>
 * Границы «построитель для своих, мост для чужих» этого не покрывало: мост целиком
 * такому классу не годится (конструктор нужен свой), а построитель заставлял писать
 * всё. Источник членов и есть недостающая середина: часть членов — лямбдами, часть —
 * от чужого типа, и <b>одним и тем же словарём</b>.
 *
 * <pre>{@code
 * NativeClass.named("Button")
 *         .field("text", StringValue.of(""))
 *         .init((self, context, args, span) -> { ... })          // своё
 *         .members(FromJava.of(JButton.class)                    // чужое
 *                 .bean("text")
 *                 .bean("enabled")
 *                 .method("doClick"))
 *         .method("onClick", Arity.exactly(1), ...)              // и снова своё
 *         .build();
 * }</pre>
 *
 * Интерфейс живёт здесь, а реализация ({@code reflect.FromJava}) — рядом с рефлексией:
 * построителю незачем знать, откуда члены берутся, а рефлексии — незачем попадать
 * в пакет, где её нет.
 */
@FunctionalInterface
public interface MemberSource {

    /**
     * Добавляет свои члены в построитель.
     * <p>
     * Зовётся в момент сборки класса, то есть при старте приложения, — и это
     * то самое место, где источник обязан проверить, что обещанное у типа есть.
     * Промах по члену у объекта — не ошибка, а {@code null} (правило языка),
     * поэтому опечатка, не пойманная здесь, доживёт до автора скрипта и будет
     * выглядеть там пропажей метода.
     */
    void contributeTo(NativeClass.Builder builder);
}
