package ru.wds.wdl.runtime;

import java.util.Objects;

/**
 * Куда скрипт печатает.
 * <p>
 * Вывод — не {@code System.out}, а зависимость, которую задаёт вызывающий. Мод для игры
 * отправит вывод скрипта в игровой чат, сервер — в лог, тест — в строку, а песочница —
 * в никуда. Если бы {@code println} писал в консоль напрямую, всё это требовало бы
 * перехвата глобального потока — то есть влияло бы на весь процесс сразу, включая
 * соседние скрипты.
 * <p>
 * Текст приходит как есть, без добавления переводов строки: их ставит сама функция
 * ({@code println} ставит, {@code print} — нет).
 */
@FunctionalInterface
public interface Output {

    void write(String text);

    /** Вывод в никуда — безопасное значение по умолчанию для встроенного движка. */
    static Output discarding() {
        return text -> {
        };
    }

    /** Вывод в стандартный поток процесса — то, что нужно консольному запуску. */
    static Output standard() {
        return System.out::print;
    }

    /**
     * Тот же вывод, но с обещанием «один {@code write} — целиком».
     * <p>
     * Нужно ровно с того момента, как внутри запуска стало больше одного потока.
     * {@code println} собирает всю строку одним вызовом ({@code Builtins}), поэтому
     * достаточно не дать двум вызовам перемешаться <b>внутри</b> строки: строки могут
     * идти в любом порядке — это потоки, — но полстроки одного потока посреди строки
     * другого нечитаемы и означают, что вывод сломан.
     * <p>
     * Декоратором, а не требованием к реализации: {@link Output} — функциональный
     * интерфейс, и приложение вправе передать {@code logger::info} или
     * {@code text -> {}}, ничего не зная про потоки. Замок здесь стоит одного
     * непересекающегося захвата на строку.
     */
    static Output serialized(Output target) {
        Objects.requireNonNull(target, "target");
        Object monitor = new Object();
        return text -> {
            synchronized (monitor) {
                target.write(text);
            }
        };
    }
}
