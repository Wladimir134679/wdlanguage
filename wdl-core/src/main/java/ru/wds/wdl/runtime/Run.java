package ru.wds.wdl.runtime;

import ru.wds.wdl.metrics.Metrics;
import ru.wds.wdl.module.ModuleSource;
import ru.wds.wdl.module.ModuleUnits;
import ru.wds.wdl.module.NativeModules;
import ru.wds.wdl.resolve.Linker;
import ru.wds.wdl.source.Span;

import java.util.Objects;

/**
 * Один запуск скрипта: всё, что принадлежит ему целиком, а не области видимости
 * и не файлу.
 * <p>
 * Раньше эти три вещи лежали полями в {@link ExecutionContext} и переносились из копии
 * в копию поодиночке. Разница не в удобстве: контекст — это <b>место</b> в выполнении
 * (какие имена видно, какой файл, какой кадр), а запуск — это <b>сеанс</b>, и живёт он
 * дольше любого места в нём. Пока их держали вместе, функция, вытащенная наружу и
 * вызванная приложением, оставалась без сеанса: {@code ExecutionContext.call} доставал
 * его у вызывающего, а у вызывающего из чужого потока его не было.
 * <p>
 * Теперь сеанс носит с собой сама функция ({@link UserFunction}) и сам класс
 * ({@link WdlClass}). Отсюда главное свойство языка на стороне встраивания:
 * <b>значение-функцию можно передать куда угодно и вызвать откуда угодно</b> — она
 * принесёт с собой свои модули, свои формы классов и свои классы ошибок. От вызывающего
 * ей нужен только вывод: печатать надо туда, где позвали.
 *
 * <h2>Что здесь мутабельно и почему</h2>
 * {@link Modules} был изменяемым всегда — «модуль выполняется один раз за запуск»
 * иначе не выразить. {@link #modules} вдобавок ещё и заменяем, но только до первой
 * инструкции скрипта: {@code withModules} и {@code withNativeModules} собирают запуск,
 * а не меняют его на ходу. Замена внутри одного {@code Run}, а не создание нового,
 * нужна ровно затем, чтобы у запуска был один сеанс от начала до конца: классы прелюдии
 * создаются раньше, чем приложение успевает выдать источник модулей, и достанься им
 * другой сеанс — {@code report()} у ошибки выполнялся бы не в том запуске, где ошибка
 * случилась.
 *
 * <h2>Потоки: замка больше нет</h2>
 * Раньше вход в скрипт снаружи брал один замок на весь сеанс, и внутри запуска
 * одновременно работал ровно один поток. Это был GIL, и держал он не удобство,
 * а корректность: области видимости, поля объектов и реестр модулей были обычными
 * неконкурентными структурами. Теперь они конкурентные — и замок снят.
 * <p>
 * <b>Что запуск обещает автору скрипта</b> (полностью — в {@code docs/threads.md}):
 * одно обращение — чтение или запись переменной, поля, элемента — атомарно и видимо
 * всем потокам. Выражение целиком — нет: {@code count = count + 1} из двух потоков
 * теряет обновления, и склеивают его {@code synchronized} на функции, {@code th.lock()}
 * и {@code th.counter()}.
 * <p>
 * <b>Режима «вернуть старый замок» здесь нет, и это решение.</b> Такой был — один
 * {@code if} на входе, — и держался он на рассуждении «чужие скрипты писались
 * в расчёте на очередь». Оказалось, что он несовместим с {@code sys.thread},
 * появившимся в том же выпуске: главный поток входит в скрипт и держит замок,
 * порождённый поток встаёт на нём, {@code t.join()} ждёт вечно — простейший
 * {@code spawn} + {@code join} вешался намертво. Совместимость с невыпущенной версией
 * не стоит мины под самой заметной возможностью языка, поэтому семантика здесь одна.
 *
 * <h2>Что теперь считается по потоку</h2>
 * Счётчик внешних входов — свойство потока, а не сеанса: цепочка «скрипт → приложение →
 * скрипт» у каждого потока своя, и складывать их в одно число значило бы, что восемь
 * рабочих потоков упираются в предел на четвёртом обороте каждый.
 */
final class Run {

    /**
     * Сколько раз в скрипт можно войти снаружи <b>на одном потоке</b>, не выйдя обратно.
     * <p>
     * Цепочка «скрипт зовёт библиотеку, библиотека зовёт функцию скрипта, та снова
     * зовёт библиотеку» съедает стек Java, а {@link ExecutionContext#MAX_CALL_DEPTH}
     * её не видит: он считает кадры скрипта, а на каждом внешнем входе цепочка кадров
     * начинается заново — новый вход и правда начало нового пути. Поэтому у входов
     * счёт свой.
     * <p>
     * Число небольшое намеренно: рекурсия через приложение — это почти всегда
     * не замысел, а зациклившийся обработчик, и упереться в предел лучше на десятом
     * обороте с внятным сообщением, чем на трёхсотом с {@code StackOverflowError}.
     */
    static final int MAX_ENTRIES = 32;

    /**
     * Реестр модулей запуска: где их искать и какие уже выполнены.
     * <p>
     * Не {@code final} — единственное поле сеанса, которое приложение задаёт после
     * создания. Почему замена, а не новый {@code Run}, разобрано в javadoc класса.
     * {@code volatile}, потому что задаётся при сборке в одном потоке, а читается
     * из всех.
     */
    private volatile Modules modules;

    /**
     * Куда сообщается время стадий этого запуска.
     * <p>
     * Свойство запуска, а не области видимости, по той же причине, что и модули:
     * «сколько заняло выполнение» — вопрос про сеанс целиком. По умолчанию метрик нет
     * и стоят они ноль ({@link Metrics#off()}); приёмник задаёт хозяин запуска
     * до первой инструкции скрипта — отсюда и {@code volatile}, как у {@link #modules}.
     */
    private volatile Metrics metrics = Metrics.off();

    /**
     * Собранные формы классов и трейтов. Один на запуск, иначе объявление класса
     * внутри функции давало бы новую форму на каждый вызов, а {@code is} перестал бы
     * узнавать свои же экземпляры.
     */
    private final Linker linker = new Linker();

    /** Классы ошибок и {@code Closeable} этого запуска — снимок прелюдии. */
    private final PreludeTypes exceptions = new PreludeTypes();

    /**
     * Открытые внешние входы <b>этого потока</b>.
     * <p>
     * Массивом из одного элемента, а не {@code ThreadLocal<Integer>}: счётчик правится
     * на каждом входе и выходе, и перекладывать бокс в карту потока дважды за вызов
     * незачем.
     */
    private final ThreadLocal<int[]> entries = ThreadLocal.withInitial(() -> new int[1]);

    /** Закрыт ли запуск. После закрытия вход в скрипт даёт остановку выполнения. */
    private volatile boolean closed;

    /** Потоки, заведённые скриптом: их же и останавливать при закрытии. */
    private final RunThreads threads = new RunThreads(this);

    /**
     * Пустой запуск: модулей нет вовсе.
     * <p>
     * Не «модули отключены флагом», а «источника не существует»: движок, встроенный
     * в приложение, не читает чужие файлы и не открывает сеть, пока его об этом
     * не попросили набором.
     *
     * @param root корневая область запуска — родитель областей всех его модулей
     */
    Run(Environment root) {
        this.modules = new Modules(new ModuleUnits(ModuleSource.none()), NativeModules.none(),
                Objects.requireNonNull(root, "root"));
    }

    Modules modules() {
        return modules;
    }

    Linker linker() {
        return linker;
    }

    PreludeTypes exceptions() {
        return exceptions;
    }

    RunThreads threads() {
        return threads;
    }

    /** Задаёт модули запуска. Зовётся при сборке, до первой инструкции скрипта. */
    void useModules(Modules replacement) {
        this.modules = Objects.requireNonNull(replacement, "modules");
    }

    Metrics metrics() {
        return metrics;
    }

    /** Задаёт приёмник метрик. Зовётся при сборке, до первой инструкции скрипта. */
    void useMetrics(Metrics replacement) {
        this.metrics = Objects.requireNonNull(replacement, "metrics");
    }

    /**
     * Открывает внешний вход в скрипт: считает вход этого потока.
     * <p>
     * Зовётся там, где управление приходит из-за границы движка, — из
     * {@link Interpreter#run} и из {@link UserFunction#call}, когда поток ещё
     * не внутри этого запуска. Изнутри скрипта не зовётся вовсе: там уже вошли,
     * и платить за это второй раз незачем.
     *
     * @param span место, которому принадлежит вопрос, — для сообщения об отказе
     */
    void enter(Span span) {
        if (closed) {
            // Не ошибка скрипта, а остановка: ресурсы запуска уже закрыты, и продолжать
            // выполнение по ним нечестно — обработчик такое ловить не должен.
            throw FatalError.runClosed(span);
        }
        int[] depth = entries.get();
        if (depth[0] >= MAX_ENTRIES) {
            throw FatalError.tooDeep(span, "Слишком длинная цепочка вызовов между скриптом "
                    + "и приложением: проверьте, не зовёт ли обработчик сам себя");
        }
        depth[0]++;
    }

    /** Закрывает внешний вход. Зовётся только в {@code finally} к {@link #enter}. */
    void leave() {
        int[] depth = entries.get();
        if (--depth[0] == 0) {
            // Не держим запись в карте потока: пул живёт дольше запуска, и оставленный
            // счётчик тянул бы за собой ссылку на закончившийся сеанс.
            entries.remove();
        }
    }

    /**
     * Работает ли текущий поток внутри этого запуска прямо сейчас.
     * <p>
     * Спрашивается у собственного счётчика, а не у вызывающего, и это принципиально.
     * Напрашивается проверить контекст — «пришёл ли вызов от {@code ExecutionContext}
     * этого запуска», — но она отвечает не на тот вопрос: приложение вправе держать
     * контекст запуска у себя и звать функцию с ним из любого потока. Контекст сказал бы
     * «свой», вход не был бы засчитан, и цепочка «скрипт → приложение → скрипт»
     * перестала бы упираться в {@link #MAX_ENTRIES}.
     */
    boolean insideCurrentThread() {
        return entries.get()[0] > 0;
    }

    /**
     * Помечает запуск закрытым: дальше вход в скрипт даёт остановку выполнения.
     * <p>
     * Нужно затем, что живые потоки скрипта переживают {@code close()} ровно столько,
     * сколько нужно им, чтобы заметить прерывание, — и позвать функцию по уже закрытым
     * модулям они не должны. Внятная остановка тут честнее, чем работа по закрытому
     * соединению.
     */
    void close() {
        closed = true;
    }

    /** Закрыт ли запуск. */
    boolean isClosed() {
        return closed;
    }
}
