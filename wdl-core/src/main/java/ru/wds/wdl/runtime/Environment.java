package ru.wds.wdl.runtime;

import ru.wds.wdl.source.Span;
import ru.wds.wdl.value.Binding;
import ru.wds.wdl.value.Value;

import java.util.Set;

/**
 * Окружение: то, во что разрешаются имена во время выполнения.
 * <p>
 * Спрятано за интерфейсом намеренно. Сейчас это поиск по цепочке областей
 * видимости — простая и понятная реализация ({@link Scope}). Позже отдельный проход
 * посчитает для каждого имени номер слота, и обращение станет чтением из массива,
 * без хеш-таблиц вообще. Интерпретатор этой замены не заметит: он знает только
 * этот интерфейс.
 * <p>
 * Пространство имён одно: функция, класс и модуль — такие же значения в таких же
 * переменных, как число. Отдельной таблицы функций, как в прошлой реализации,
 * здесь нет и не будет — иначе функцию нельзя передать аргументом и вернуть из функции.
 */
public interface Environment {

    /** Значение имени или {@code null}, если имя не определено ни здесь, ни выше. */
    Value lookup(String name);

    /**
     * То же чтение, но с правом выполнить код: за именем внутри класса может стоять
     * {@linkplain ru.wds.wdl.value.Property свойство}, и прочитать его — значит позвать
     * getter.
     * <p>
     * Отдельная перегрузка, а не поле в окружении, потому что контекст выполнения
     * приходит от вызывающего и меняется на каждом кадре: глубина вызовов,
     * трассировка, вывод. Область о выполнении не знает и знать не должна — она
     * только доводит контекст до того слоя, который умеет позвать код.
     * <p>
     * Реализация по умолчанию игнорирует контекст: свойства бывают ровно у одного
     * вида областей, и заставлять остальные знать о них незачем. Область, у которой
     * есть внешняя, обязана перегрузку <b>передать дальше</b> — иначе слой с полями
     * останется за спиной у поиска.
     */
    default Value lookup(String name, ExecutionContext context, Span span) {
        return lookup(name);
    }

    /**
     * Значение имени <b>в самой этой области</b>, без похода наружу, или {@code null}.
     * <p>
     * Нужно там, где перекрытие внешнего имени законно, а повторное объявление своего —
     * нет: развёрнутый {@code import} внутри функции вправе затенить класс, объявленный
     * снаружи, но не вправе молча заменить тот, что объявлен рядом с ним.
     */
    Value lookupHere(String name);

    boolean isDefined(String name);

    /** Заводит имя в этой области, перекрывая одноимённое из внешней. */
    void define(String name, Value value);

    /**
     * Заводит имя, которое нельзя переприсвоить: {@code const LIMIT = 10}.
     * <p>
     * Заморожено именно имя, а не значение: {@code const items = [1, 2]} запрещает
     * {@code items = [3]}, но не {@code items[0] = 5}. Значение о том, в какой переменной
     * оно лежит, не знает и знать не должно — иначе один и тот же массив, положенный
     * в две переменные, вёл бы себя по-разному.
     * <p>
     * Уже занятое константой имя здесь не проверяется — по той же причине, по которой
     * {@link #assign} не заводит отсутствующее: у окружения нет места в исходнике,
     * а диагностика без места бесполезна. Решение принимает интерпретатор.
     */
    void defineConstant(String name, Value value);

    /**
     * Заводит имя, которое живёт в другом месте: то, что делает развёрнутый
     * {@code import}.
     * <p>
     * Не копия значения, а {@link Binding связка}: модуль выполняется один раз,
     * и присваивание такому имени обязано дойти до него — иначе функции модуля
     * продолжили бы считать по-старому, а второй импортёр не увидел бы ничего.
     * <p>
     * Заводится и стирается имя здесь так же, как обычное: своё объявление вытесняет
     * связку, связка вытесняет ранее объявленное имя. Затенение внешней области —
     * то же самое, что у {@link #define}.
     * <p>
     * Реализация по умолчанию кладёт снимок значения — это ровно то, что делал
     * развёрнутый импорт раньше. Так окружение, написанное приложением
     * ({@link ru.wds.wdl.module.Library}), продолжает работать, не зная о связках вовсе.
     */
    default void defineAlias(String name, Binding binding) {
        define(name, binding.value());
    }

    /**
     * Есть ли константа с этим именем <b>в самой этой области</b>, без похода наружу.
     * <p>
     * Наружу смотреть нельзя намеренно: вложенная область вправе объявить свою константу
     * с тем же именем — это затенение, а не переопределение, и работает оно так же,
     * как у объявления функции.
     */
    boolean isConstantHere(String name);

    /**
     * Присваивает значение существующему имени — в той области, где оно определено.
     *
     * @return {@link Assignment#ABSENT}, если имя нигде не определено — заводить его молча
     *         не дело окружения, решение принимает интерпретатор; {@link Assignment#CONSTANT},
     *         если имя нашлось, но заморожено {@code const}
     */
    Assignment assign(String name, Value value);

    /**
     * То же присваивание, но с правом выполнить код: за именем может стоять свойство,
     * и записать его — значит позвать setter. Причина отдельной перегрузки та же,
     * что у {@link #lookup(String, ExecutionContext, Span)}.
     */
    default Assignment assign(String name, Value value, ExecutionContext context, Span span) {
        return assign(name, value);
    }

    /**
     * Куда добавлять члены значениям, или {@code null}, если добавлять некуда.
     * <p>
     * Через область, а не вторым методом у {@link ru.wds.wdl.module.Library}: таблица
     * членов принадлежит запуску, а библиотека видит только область — и звать её
     * {@code installTo} умеют все, кто заводит запуск, тогда как второй метод легко
     * забыть. Реализация по умолчанию отвечает {@code null}: область, написанная
     * приложением, о запуске не знает, и заставлять её знать незачем — библиотека
     * узнаёт об этом сразу и на месте, а не из {@code NullPointerException}
     * в середине установки.
     */
    default ru.wds.wdl.value.MemberRegistry members() {
        return null;
    }

    /**
     * Имена, заведённые <b>в этой самой области</b>, без похода наружу.
     * <p>
     * Спрашивать содержимое области нужно двоим, и оба — снаружи выполнения: панели
     * переменных отладчика, которой кадр без списка имён показать нечего, и дополнению
     * в REPL, где предлагать надо то, что человек уже завёл. Самому интерпретатору
     * перечисление не нужно никогда — поэтому оно и не обязательно.
     * <p>
     * Реализация по умолчанию отвечает пустым множеством: область, написанная
     * приложением ({@link ru.wds.wdl.module.Library}), о таком вопросе не знает,
     * и заставлять её знать незачем — пустой ответ честен и ничего не ломает.
     */
    default Set<String> namesHere() {
        return Set.of();
    }

    /**
     * Все имена, видимые отсюда: свои плюс те, что дают внешние области.
     * <p>
     * Ближняя область сильнее: имя, перекрытое здесь, встречается в наборе один раз,
     * и это то же правило, по которому его находит {@link #lookup}.
     */
    default Set<String> names() {
        return namesHere();
    }

    /** Вложенная область: тело функции, блок, итерация цикла. */
    Environment child();
}
