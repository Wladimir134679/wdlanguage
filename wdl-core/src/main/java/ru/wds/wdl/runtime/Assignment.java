package ru.wds.wdl.runtime;

/**
 * Чем закончилось присваивание существующему имени.
 * <p>
 * Перечисление, а не {@code boolean}, ровно по одной причине: «имени нигде нет» и «имя
 * есть, но менять его нельзя» — два разных ответа <b>одного и того же</b> поиска по
 * цепочке областей. Свести их к «получилось / не получилось» значило бы искать имя
 * второй раз, чтобы выяснить, почему не получилось, и держать два обхода в согласии
 * руками — ровно тот класс ошибок, от которого избавлено всё остальное окружение.
 * <p>
 * <b>Новый исход обязателен к разбору в {@code Interpreter.VariablePlace#write}.</b>
 * Компилятор об этом не напомнит: {@code switch}-инструкция по константам перечисления
 * на полноту не проверяется, в отличие от выражения и разбора по образцу.
 */
public enum Assignment {

    /** Записано в ту область, где имя объявлено. */
    DONE,

    /** Имени нет ни здесь, ни выше: заводить его — решение интерпретатора, не окружения. */
    ABSENT,

    /** Имя объявлено через {@code const}: значение задаётся один раз, и оно уже задано. */
    CONSTANT
}
