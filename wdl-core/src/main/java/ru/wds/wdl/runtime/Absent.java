package ru.wds.wdl.runtime;

/**
 * Пропуск цепочки безопасного обращения: звено {@code ?.} увидело пустой получатель
 * и передаёт «дальше не идём» границе цепочки.
 * <p>
 * Это не ошибка и не сигнал управления выполнением — ловит его ровно один метод
 * интерпретатора ({@code visitOptionalChain}) и превращает в значение {@code null}.
 * Наружу он не выходит и скрипту не виден.
 * <p>
 * <b>Почему исключение, а не особое значение-часовой.</b> Часового каждое следующее
 * звено обязано было бы проверять: и чтение по ключу, и вызов, и раскладка аргументов.
 * Это самые горячие места движка, и платили бы в них все — ради случая, который
 * в них не наступает. Исключение платит только на пустом пути и ровно один раз
 * на цепочку. Прецедент в движке стоит: {@code break}, {@code continue} и
 * {@code return} — тоже сигналы, а не код возврата в каждом узле
 * (см. {@link ControlSignal}).
 * <p>
 * Синглтон без стека вызовов и без сообщения: нести ему нечего, а заполнение
 * стектрейса описывало бы путь по методам интерпретатора, который никому не нужен.
 * <p>
 * <b>Границу чужого кода не пересекает.</b> Бросается он при чтении получателя,
 * то есть до вычисления аргументов и до входа в функцию, — между броском и границей
 * цепочки стоят только кадры самого интерпретатора. Строка в {@link Foreign} всё равно
 * есть: правило «что своё, что чужое» должно быть полным в одном месте.
 */
final class Absent extends RuntimeException {

    static final Absent INSTANCE = new Absent();

    private Absent() {
        super(null, null, false, false);
    }
}
