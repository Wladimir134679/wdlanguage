package ru.wds.wdl.embed;

import ru.wds.wdl.source.Span;
import ru.wds.wdl.value.CallContext;
import ru.wds.wdl.value.Value;

/**
 * Чтение свойства нативного класса — Java-лямбда вместо дерева.
 * <p>
 * От {@link NativeMethod} отличается ровно одним: {@link Args} здесь нет. Свойство
 * читают обращением, а у обращения аргументов не бывает — передавать туда просто
 * нечем, и параметр, который всегда пуст, был бы обманом.
 * <p>
 * <b>Когда свойство, а когда поле.</b> Правило нативного класса — «что выразимо
 * значением, лежит полем»: путь к файлу это строка, значит {@code .field("path")},
 * и тогда {@code f.path}, {@code println(f)} и перебор работают сами собой, без
 * единой строчки в библиотеке. Свойство нужно там, где значение живёт <b>только</b>
 * в Java-объекте и меняется за его спиной: размер окна, которое тянет мышью
 * пользователь, позиция в открытом потоке, состояние соединения. Полем такое
 * не сделать — оно устареет к следующему обращению.
 */
@FunctionalInterface
public interface NativeGetter {

    Value get(NativeInstance self, CallContext context, Span span);
}
