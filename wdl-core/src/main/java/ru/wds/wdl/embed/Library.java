package ru.wds.wdl.embed;

import ru.wds.wdl.runtime.Environment;

/**
 * Набор имён, который приложение кладёт в область видимости скрипта: функции,
 * классы, константы.
 * <p>
 * Библиотека ничего не «регистрирует» в движке и никуда не прописывается — она
 * просто заводит имена в переданной области. Отсюда всё остальное: подключить её
 * можно к одному запуску и не подключить к другому, две библиотеки с одинаковым
 * именем разойдутся по разным областям, а тест может подсунуть свою реализацию,
 * определив то же имя после.
 * <p>
 * Это то же самое, что делает {@code Builtins} для {@code println} и {@code len}:
 * отдельной таблицы библиотек в языке нет, как нет и таблицы функций.
 */
public interface Library {

    /** Имя для сообщений и диагностики: {@code "std"}. */
    String name();

    /**
     * Кладёт имена библиотеки в область видимости.
     *
     * @return та же область — чтобы вызов удобно встраивался в цепочку
     */
    Environment installTo(Environment scope);

    /**
     * Отпускает ресурсы, заведённые библиотекой: соединение, клиент, открытый канал.
     * <p>
     * По умолчанию не делает ничего, и так у большинства: {@code pow} и {@code sqrt}
     * закрывать нечего. Нужен этот метод тем, кто заводит что-то живое, — и зовёт его
     * хозяин запуска, когда запуск кончился ({@code Modules.shutdown} через
     * {@code ExecutionContext.shutdownModules}).
     * <p>
     * Ошибка здесь не должна ронять уже отработавший скрипт, поэтому закрывающий
     * её переживает и продолжает закрывать остальные.
     */
    default void close() {
    }
}
