package ru.wds.wdl.resolve;

import ru.wds.wdl.ast.expr.FunctionExpr;

/**
 * Метод в плоской таблице класса.
 * <p>
 * Таблица собрана один раз при объявлении — из родителя, трейтов и собственных
 * методов, — поэтому поиска по цепочке во время выполнения нет: обращение к методу
 * стоит столько же, сколько обращение к полю, и не зависит от глубины наследования.
 * <p>
 * {@link #declaredIn()} — не то же самое, что класс экземпляра, и разница
 * принципиальна. Метод {@code Shape.text()}, унаследованный кругом, замыкает область,
 * где объявлен <b>Shape</b>, и его {@code super} — родитель Shape, а не родитель круга.
 * А вот обращение по голому имени внутри такого метода ищется в классе экземпляра,
 * то есть виртуально: {@code area()} внутри {@code Shape.text()} найдёт реализацию круга.
 */
public record MethodSlot(String name, FunctionExpr declaration, Shape declaredIn) {
}
