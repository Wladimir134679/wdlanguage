package ru.wds.wdl.resolve;

import ru.wds.wdl.ast.expr.FunctionExpr;

/**
 * Поле экземпляра и то, откуда берётся его значение.
 * <p>
 * Источник — всегда параметр чьего-то заголовка: своего класса, класса-предка
 * или типажа. Больше вариантов и не бывает, потому что отдельного объявления полей
 * в языке нет: заголовок и есть список полей.
 * <p>
 * Слоты собираются в одну плоскую таблицу в порядке «родитель → типажи слева
 * направо → сам класс», и одинаковые имена схлопываются по правилу «побеждает
 * последний»: позиция остаётся от первого вхождения, значение — от последнего.
 * Поэтому при создании каждое поле записывается <b>ровно один раз</b>, и никакого
 * «сначала записали, потом затёрли» не бывает.
 *
 * @param owner      чей заголовок задаёт значение
 * @param paramIndex номер параметра в этом заголовке
 */
public record FieldSlot(String name, Shape owner, int paramIndex) {

    public FunctionExpr.Param param() {
        return owner.params().get(paramIndex);
    }
}
