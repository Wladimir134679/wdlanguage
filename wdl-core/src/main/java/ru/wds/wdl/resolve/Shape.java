package ru.wds.wdl.resolve;

import ru.wds.wdl.ast.expr.FunctionExpr;

import java.util.List;
import java.util.Map;

/**
 * Форма класса или типажа: всё, что известно о нём <b>до выполнения</b>.
 * <p>
 * Форма собирается один раз, при разборе объявлений, и не зависит ни от области
 * видимости, ни от значений: плоские таблицы полей и методов, цепочка предков,
 * набор типажей. Именно поэтому невыполненное требование типажа и круг
 * в наследовании ловятся там, где сделаны, а не через час работы скрипта.
 * <p>
 * Разделение простое: <b>форма — имена и порядок, значение — замыкание и данные.</b>
 * {@code ru.wds.wdl.runtime.WdlClass} оборачивает форму областью объявления, поэтому
 * класс, объявленный внутри функции, при каждом вызове даёт новое значение, но форму
 * переиспользует ту же.
 */
public sealed interface Shape permits ClassShape, TraitShape {

    String name();

    /** Заголовок: список параметров, он же список полей. */
    List<FunctionExpr.Param> params();

    /**
     * Плоская таблица полей: имя → откуда берётся значение.
     * <p>
     * Порядок — порядок печати экземпляра: родительские, из типажей, свои.
     */
    Map<String, FieldSlot> fields();

    /** Плоская таблица методов: имя → объявление и то, где оно записано. */
    Map<String, MethodSlot> methods();
}
