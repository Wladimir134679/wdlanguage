package ru.wds.wdl.resolve;

import ru.wds.wdl.value.TraitValue;

/**
 * Трейт, у которого есть форма, — то есть трейт, которым можно связать класс.
 * <p>
 * {@link TraitValue} говорит только «это трейт»: интерфейс открытый, и его вправе
 * реализовать кто угодно — скажем, мост, показывающий скрипту Java-интерфейс. Но
 * подмешать в {@code class X with T} можно не всякий трейт, а лишь тот, чьи требования
 * умеет проверить {@link Linker}, — и вот это обещание и есть здесь.
 * <p>
 * Реализаций две, и ядру всё равно, какая перед ним: трейт, написанный на wdl,
 * и трейт, объявленный приложением построителем в {@code wdl-bridge}. Раньше на
 * втором месте стояло имя конкретного класса из пакета встраивания, и ядро из-за
 * одной проверки {@code instanceof} зависело от построителя, которым само никогда
 * не пользуется. Теперь зависимость идёт в одну сторону: построитель знает про
 * форму, ядро про построитель — нет.
 */
public interface DeclaredTrait extends TraitValue {

    /** Форма трейта: требования и объявленные поля. Одна на всю его жизнь. */
    TraitShape shape();
}
