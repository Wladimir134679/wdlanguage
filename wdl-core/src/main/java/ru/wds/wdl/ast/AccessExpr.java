package ru.wds.wdl.ast;

import ru.wds.wdl.source.Span;

import java.util.Objects;

/**
 * Обращение к содержимому значения: {@code точка.x}, {@code массив[0]},
 * {@code настройки["цвет"]}, {@code данные.строки[3].имя}.
 * <p>
 * <b>Центральное решение языка: обращение одно.</b> Точка и квадратные скобки —
 * не две разные операции, а две записи одной. {@code точка.x} — это в точности
 * {@code точка["x"]}: точка лишь избавляет от кавычек, когда ключ известен заранее
 * и выглядит как имя. Парсер сам превращает {@code .x} в ключ-строку, и до
 * интерпретатора обе формы доходят абсолютно одинаковыми узлами.
 * <p>
 * Что это даёт:
 * <ul>
 *   <li>поле объекта, элемент словаря и элемент массива — один механизм и один
 *       набор правил, а не три похожих, расходящихся со временем;</li>
 *   <li>ключ можно вычислить: {@code настройки[имяПоля]} работает там же, где
 *       {@code настройки.цвет}, без отдельного синтаксиса вроде рефлексии;</li>
 *   <li>новый тип-контейнер (класс, модуль, обёртка над Java-объектом) достаточно
 *       научить отвечать на обращение по ключу — и он немедленно поддерживает обе
 *       записи, включая перебор полей;</li>
 *   <li>у присваивания та же структура: разобрать {@code a.b[0] = 1} — значит
 *       вычислить всё, кроме последнего ключа, и записать по нему. Одна реализация
 *       вместо ветвлений по форме записи.</li>
 * </ul>
 * Подробности и правила по типам — в {@code docs/access.md}.
 * <p>
 * Цепочка обращений собирается вложением, а не списком: {@code a.b.c} — это
 * {@code Access(Access(a, "b"), "c")}. Так у каждого шага свой корректный
 * {@link Span}, а вычисление промежуточного значения не требует особого случая —
 * это обычное вычисление левого поддерева.
 *
 * @param target значение, к которому обращаются
 * @param key    ключ: для записи через точку — строковый литерал, для скобок — любое выражение
 * @param style  какой записью это было в исходнике; на семантику не влияет
 * @param span   место в исходнике: от начала {@code target} до закрывающей скобки или конца имени
 */
public record AccessExpr(Expr target, Expr key, AccessStyle style, Span span) implements Expr {

    public AccessExpr {
        Objects.requireNonNull(target, "target");
        Objects.requireNonNull(key, "key");
        Objects.requireNonNull(style, "style");
        Objects.requireNonNull(span, "span");
    }

    /**
     * Имя поля, если обращение записано через точку. Нужно диагностике и инструментам:
     * «у объекта нет поля x» читается лучше, чем «нет ключа "x"». На вычисление
     * не влияет — интерпретатор всегда работает с {@link #key()}.
     */
    public String fieldName() {
        if (style == AccessStyle.DOT && key instanceof LiteralExpr literal) {
            return literal.value().display();
        }
        return null;
    }

    @Override
    public String toString() {
        return style == AccessStyle.DOT
                ? target + "." + fieldName()
                : target + "[" + key + "]";
    }
}
