package ru.wds.wdl.ast;

import ru.wds.wdl.ast.expr.Expr;
import ru.wds.wdl.ast.stmt.Stmt;
import ru.wds.wdl.source.Span;

/**
 * Узел синтаксического дерева.
 * <p>
 * Единственное, что есть у любого узла, — его место в исходнике. Ни выполнения,
 * ни ссылок на окружение, ни изменяемых полей: дерево, полученное от парсера,
 * можно печатать, сравнивать, кэшировать и запускать одновременно в нескольких
 * потоках, потому что оно ничего о выполнении не знает.
 * <p>
 * Иерархия {@code sealed}: выражения ({@link Expr}) дают значение, инструкции
 * ({@link Stmt}) выполняются ради действия, {@link Program} — корень разобранного
 * скрипта. Дальше сюда придут объявления.
 */
public sealed interface Node permits Expr, Stmt, Program, Fragment {

    /** Интервал исходного текста, который занял этот узел. */
    Span span();
}
