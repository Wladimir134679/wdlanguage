package ru.wds.wdl.ast.stmt;

import ru.wds.wdl.ast.expr.Expr;
import ru.wds.wdl.source.Span;

import java.util.Objects;

/**
 * Объявление константы: {@code const LIMIT = 10}.
 * <p>
 * Единственное объявление переменной в языке: обычное имя по-прежнему заводится первым
 * присваиванием, и отдельного {@code var} не будет. Отдельный вид инструкции, а не признак
 * у {@link AssignStmt}, по двум причинам, и обе те же, что у {@link DefDeclStmt}. Во-первых,
 * объявление <b>заводит</b> имя в текущей области, а присваивание ищет его снаружи и меняет
 * там, где нашло; отсюда и затенение — вложенный блок объявляет свою константу, не трогая
 * внешнюю. Во-вторых, слева от {@code =} здесь стоит имя, и только имя: {@code const a.b = 1}
 * бессмысленно, потому что заморозить можно имя, а не ячейку внутри чужого значения.
 * <p>
 * <b>Заморожено именно имя.</b> {@code const items = [1, 2]} запрещает {@code items = [3]},
 * но не {@code items[0] = 5}. Значение о том, в какой переменной оно лежит, не знает и знать
 * не должно — иначе один и тот же массив, положенный в две переменные, вёл бы себя
 * по-разному в зависимости от того, через какую его трогают.
 * <p>
 * В отличие от {@code def}, {@code class} и {@code trait}, константа <b>не помечается</b>
 * до начала выполнения: у неё выражение-инициализатор, и вычислять его до первой инструкции
 * скрипта значило бы завести вторую, невидимую фазу выполнения. Поэтому функция, объявленная
 * выше константы, её видит — если вызвана после объявления.
 *
 * @param name     имя, которое заводится в текущей области
 * @param nameSpan место самого имени: им подчёркивается повторное объявление, и подчёркивать
 *                 надо имя, а не всю инструкцию
 * @param value    начальное значение; обязательно, потому что второго присваивания не будет
 * @param span     место в исходнике от {@code const} до конца выражения
 */
public record ConstDeclStmt(String name, Span nameSpan, Expr value, Span span) implements Stmt {

    public ConstDeclStmt {
        Objects.requireNonNull(name, "name");
        Objects.requireNonNull(nameSpan, "nameSpan");
        Objects.requireNonNull(value, "value");
        Objects.requireNonNull(span, "span");
    }

    @Override
    public String toString() {
        return "const " + name + " = " + value;
    }
}
