package ru.wds.wdl.ast.stmt;

/**
 * Как возврат был записан в исходнике.
 * <p>
 * Смысла у возврата от этого не прибавляется: {@code return a + 1;} и {@code => a + 1}
 * дают один и тот же {@link ReturnStmt}. Форма записи сохраняется ради тех, кому важен
 * исходный текст: форматтер обязан вернуть стрелку туда, где была стрелка, а не переписать
 * её на {@code return}. Тот же мотив, что у {@link ru.wds.wdl.ast.expr.AccessStyle}.
 * <p>
 * Формы тела функции здесь нет и не нужно: блок, одиночная инструкция и стрелка видны
 * по самому дереву — {@code body instanceof BlockStmt} против {@code body instanceof ReturnStmt}
 * с той или иной формой записи. Перечисление хранит ровно то, что из дерева иначе
 * не восстановить.
 */
public enum ReturnStyle {

    /** {@code return a + 1;} — со словом и обязательной точкой с запятой. */
    KEYWORD,
    /**
     * {@code => a + 1} — стрелкой. Значение обязательно, поэтому точка с запятой
     * не нужна: следующая инструкция от такого возврата отделяется однозначно.
     */
    ARROW
}
