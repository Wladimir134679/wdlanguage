package ru.wds.wdl.ast.expr;

import ru.wds.wdl.source.Span;

import java.util.Objects;

/**
 * Граница цепочки безопасного обращения: место, где пропуск звена становится
 * значением {@code null}.
 * <p>
 * <b>Зачем узел, если у звена уже есть флаг.</b> Флаг отвечает на вопрос «пропускать
 * ли это звено», а замыкание в языке относится не к звену, а ко всей цепочке:
 * {@code user?.profile.name} при пустом {@code user} даёт {@code null}, а не ошибку
 * на {@code .name}. Значит, у замыкания есть граница, и она — часть смысла записи.
 * То, что влияет на смысл, обязано быть видно в дереве: в дампе, в ожидании теста,
 * в обходе инструментами. Спрятанное в булев признак «я последний в цепочке»,
 * оно было бы неотличимо от соседнего звена.
 * <p>
 * <b>Почему замыкание на цепочку, а не на звено.</b> Обратную дисциплину (Kotlin)
 * держит компилятор: {@code a?.b.c} там просто не соберётся. Языку без типов
 * поймать это нечем, поэтому звеньевое правило оставляло бы ошибку, невидимую
 * ни при написании, ни при первом запуске, — она ждала бы того единственного
 * прогона, где значение окажется пустым. Ровно от этого {@code ?.} и заводился.
 * <p>
 * Второй довод решает окончательно: <b>метода в языке нет</b>.
 * {@code logger?.info("go")} — это обращение и вызов его результата, и при
 * звеньевой дисциплине писать пришлось бы {@code logger?.info?.()}. Записи,
 * где {@code ?.} нужен дважды на одно человеческое намерение, в языке быть не должно.
 * <p>
 * <b>Узел появляется, только если в цепочке есть {@code ?.}.</b> Обычные
 * {@code a.b.c} остаются тем же деревом, что и были, — ни лишнего уровня,
 * ни лишней работы.
 *
 * @param inner цепочка целиком: самое внешнее звено со всеми вложенными
 * @param span  место в исходнике; совпадает с интервалом {@code inner}
 */
public record OptionalChainExpr(Expr inner, Span span) implements Expr {

    public OptionalChainExpr {
        Objects.requireNonNull(inner, "inner");
        Objects.requireNonNull(span, "span");
    }

    @Override
    public String toString() {
        return inner.toString();
    }
}
