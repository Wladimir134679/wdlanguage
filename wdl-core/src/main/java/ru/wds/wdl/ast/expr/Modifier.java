package ru.wds.wdl.ast.expr;

/**
 * Модификатор функции: слово перед {@code def}, меняющее не тело, а правила вызова.
 * <p>
 * Перечислением, а не набором признаков {@code boolean} в {@link FunctionExpr}, и это
 * решение на будущее: {@code record} в {@code sealed}-иерархии меняется дорого — правка
 * задевает каждого посетителя, — а второй модификатор почти неизбежен. Добавить элемент
 * сюда дешевле, чем добавить поле туда.
 */
public enum Modifier {

    /**
     * {@code synchronized def bump() { ... }} — вызовы этой функции не идут одновременно.
     * <p>
     * Замок принадлежит <b>значению-функции</b>, а не имени: замыкание, созданное дважды,
     * даёт два значения и два замка — и это верно, у них разное захваченное состояние.
     * У метода класса замок — <b>экземпляр</b>, а не метод: метод защищает поля своего
     * объекта, и два разных объекта мешать друг другу не должны.
     */
    SYNCHRONIZED;

    /** Как слово пишется в исходнике — тем же текстом, что и токен. */
    public String text() {
        return name().toLowerCase(java.util.Locale.ROOT);
    }
}
