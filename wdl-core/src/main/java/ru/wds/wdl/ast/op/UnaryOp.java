package ru.wds.wdl.ast.op;

/**
 * Унарная операция.
 * <p>
 * Здесь только смысл операции, её написание и {@linkplain #member() имя члена},
 * которым она перегружается. Приоритет — свойство синтаксиса, а не дерева, и живёт
 * в таблице парсера: дерево уже разобрано, спорить о порядке применения в нём не о чем.
 * <p>
 * Унарный член отличается от бинарного <b>арностью</b>, а не именем:
 * {@code def `-`()} — смена знака, {@code def `-`(right)} — вычитание. Больше их
 * различать нечем, и незачем: арность известна по тексту объявления.
 */
public enum UnaryOp {

    /** {@code -x} — смена знака. */
    NEGATE("-", "-"),
    /** {@code +x} — ничего не меняет, но требует числа: опечатку видно сразу. */
    PLUS("+", "+"),
    /**
     * {@code !x} — логическое отрицание, результат всегда логический.
     * <p>
     * Единственная унарная операция без члена: ядро на ней не падает никогда —
     * достоверность есть у любого значения, — и запасному пути нечего было бы ловить.
     */
    NOT("!", null),
    /** {@code ~x} — побитовое дополнение, только для целых. */
    COMPLEMENT("~", "~");

    private final String symbol;
    private final String member;

    UnaryOp(String symbol, String member) {
        this.symbol = symbol;
        this.member = member;
    }

    public String symbol() {
        return symbol;
    }

    /** Имя члена без параметров, которым операция перегружается, или {@code null}. */
    public String member() {
        return member;
    }

    /** Есть ли у операции член, которым её можно перегрузить. */
    public boolean overloadable() {
        return member != null;
    }

    @Override
    public String toString() {
        return symbol;
    }
}
