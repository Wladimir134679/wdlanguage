package ru.wds.wdl.ast.stmt;

import ru.wds.wdl.source.Span;

import java.util.Objects;

/**
 * Отложенное действие: {@code defer file.close()}.
 * <p>
 * Выполняется <b>на выходе из своей области видимости</b>, а не из функции. Область
 * в языке создаёт {@link BlockStmt блок}, и {@code defer} просто следует общему
 * правилу — второго понятия «где кончается область» язык не заводит.
 * Отсюда же главное отличие от Go: там {@code defer} привязан к функции, и цикл,
 * открывающий файл на каждом проходе, копит дескрипторы до самого выхода — известная
 * ловушка, которую приходится обходить лямбдой. Привязка к области убирает её
 * по построению.
 * <p>
 * Порядок обратный: последний записанный выполняется первым. Иначе нельзя было бы
 * освобождать ресурсы, зависящие друг от друга.
 * <p>
 * <b>Записывается после успешного захвата</b> — в этом вся разница с {@code finally}.
 * Блок {@code finally} существует независимо от того, дошло ли выполнение до захвата,
 * и потому в примерах на Java обрастает проверками на {@code null}; отложенного
 * действия просто нет, пока {@code open} не вернулся.
 *
 * @param body одна инструкция (обычно вызов) или блок
 */
public record DeferStmt(Stmt body, Span span) implements Stmt {

    public DeferStmt {
        Objects.requireNonNull(body, "body");
        Objects.requireNonNull(span, "span");
    }
}
