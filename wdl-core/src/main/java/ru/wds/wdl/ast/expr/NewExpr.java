package ru.wds.wdl.ast.expr;

import ru.wds.wdl.source.Span;

import java.util.List;

/**
 * Создание экземпляра: {@code new Point(20, 30)}.
 * <p>
 * Слева от скобок стоит не имя, а <b>выражение</b>: {@code new kinds[0](1, 2)}
 * и {@code new cls(a, b)} законны, потому что класс — обычное значение в обычной
 * переменной. Слово {@code new} говорит не «здесь имя класса», а «создай экземпляр
 * того, что получится слева».
 * <p>
 * {@code new} забирает себе ровно одно обращение и один список аргументов, а всё,
 * что идёт дальше, применяется уже к экземпляру: {@code new Circle(5).area()} —
 * это вызов {@code area} у созданного круга, а не создание по результату вызова.
 * Как в Java и по той же причине: иначе такую запись пришлось бы всё время
 * заключать в скобки.
 * <p>
 * Отдельный узел, а не {@link CallExpr} с флагом, потому что стоят эти две вещи
 * разного: вызов считает, создание заводит новое состояние. Разница видна в тексте
 * скрипта и должна быть видна в дереве.
 */
public record NewExpr(Expr callee, List<Expr> arguments, Span span) implements Expr {
}
