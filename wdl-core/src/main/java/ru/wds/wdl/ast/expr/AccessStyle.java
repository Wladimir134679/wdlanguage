package ru.wds.wdl.ast.expr;

/**
 * Как обращение было записано в исходнике.
 * <p>
 * Смысла у обращения от этого не прибавляется: {@code a.x} и {@code a["x"]} —
 * одно и то же (см. {@link AccessExpr}). Форма записи сохраняется ради тех, кому
 * важен исходный текст: форматтер должен вернуть точку туда, где была точка,
 * а диагностика — сказать «нет поля x», а не «нет ключа "x"», если человек писал
 * через точку.
 */
public enum AccessStyle {

    /** {@code значение.имя} — ключ известен на этапе разбора. */
    DOT,
    /** {@code значение[выражение]} — ключ вычисляется. */
    BRACKET
}
