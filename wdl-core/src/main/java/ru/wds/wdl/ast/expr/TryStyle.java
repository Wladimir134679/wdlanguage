package ru.wds.wdl.ast.expr;

/**
 * Какой из двух коротких форм записан {@link TryExpr}.
 * <p>
 * Разница не в записи, а в смысле: одна форма говорит «мне не важно, что именно
 * случилось», вторая — «здесь ошибки быть не может».
 */
public enum TryStyle {

    /**
     * {@code try? выражение} — ошибка даёт {@code null}.
     * <p>
     * Ровно тот случай, ради которого иначе пишут {@code catch (e) {}} — самую вредную
     * конструкцию в языках с исключениями, потому что по ней не видно, проглотили её
     * намеренно или забыли дописать. Здесь это видно в строке.
     */
    OPTIONAL("try?"),

    /**
     * {@code try! выражение} — утверждение, а не подавление.
     * <p>
     * Не «игнорирует» ошибку, а объявляет её невозможной: если она всё-таки случилась,
     * это дефект скрипта, и ловить его обработчиком неправильно — поэтому ошибка
     * становится {@code FatalError} и уходит в хост с исходной причиной. Так же
     * устроены {@code try!} в Swift и {@code unwrap()} в Rust.
     */
    FORCED("try!");

    private final String text;

    TryStyle(String text) {
        this.text = text;
    }

    /** Как форма записана в тексте — слитно. */
    public String text() {
        return text;
    }
}
