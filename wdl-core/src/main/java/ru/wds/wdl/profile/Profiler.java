package ru.wds.wdl.profile;

/**
 * Куда движок сообщает о вызовах: приёмник профиля.
 * <p>
 * Профилировщик — <b>зависимость, а не статика</b>, ровно как {@code Metrics}
 * и {@code Output}: его создаёт хозяин запуска и передаёт в контекст. Счётчик
 * в статическом поле сложил бы вместе два интерпретатора, работающих в одном процессе.
 *
 * <h2>Чем он отличается от метрик</h2>
 * {@code Metrics} отвечает на вопрос «во что ушло время запуска» — стадий там четыре,
 * и стоят они ноль. Профиль отвечает на другой вопрос — «какая функция самая горячая»,
 * — и стоит он двух обращений к часам на каждый вызов. Поэтому это разные объекты
 * с разными способами включения, а не пятая стадия в том же перечислении.
 *
 * <h2>Почему счётчики, а не выборка стека</h2>
 * Профиль здесь <b>инструментирующий</b>: точка съёма стоит там же, где движок и так
 * делает шаг ({@code Run.checkpoint}), и потому число вызовов в отчёте — точное,
 * а не оценка. Выборка (сэмплирование) дешевле на горячем коде, но требует, чтобы
 * стек скрипта существовал как структура данных, — а его нет: цепочка
 * {@code runtime.Frame} разворачивается только при броске ошибки, и заводить ради
 * профиля второй стек в каждом вызове значило бы платить за это всегда.
 * Скрипт при включённом профиле идёт медленнее — это честная цена, и она названа
 * в {@code docs/profiling.md}.
 *
 * <h2>Выключенный профиль стоит ноль</h2>
 * {@link #off()} — синглтон, чей {@code enter} отдаёт себя же, а {@code close()} пуст.
 * Точка съёма спрашивает {@link #recording()} до того, как построить {@link CallSite},
 * — то же правило, что у {@code Limits.counting()}: сначала чтение поля и сравнение,
 * потом всё остальное.
 * <pre>{@code
 * Profiler profiler = run.profiler();
 * if (!profiler.recording()) {
 *     return invoke(context, arguments, span);
 * }
 * Probe probe = profiler.enter(site());
 * try {
 *     return invoke(context, arguments, span);
 * } finally {
 *     probe.close();
 * }
 * }</pre>
 */
public interface Profiler {

    /**
     * Открывает счёт вызова. Закрывать обязательно — из {@code finally}.
     *
     * @param site что вызвали и где оно объявлено
     */
    Probe enter(CallSite site);

    /**
     * Считает ли этот приёмник хоть что-нибудь.
     * <p>
     * Спрашивается в точке съёма перед постройкой {@link CallSite}: ключ профиля —
     * объект, и создавать его там, где профиль выключен, значит платить за то,
     * о чём не просили.
     */
    boolean recording();

    /** Ничего не считает и ничего не помнит — значение по умолчанию у каждого запуска. */
    static Profiler off() {
        return NoProfiler.INSTANCE;
    }

    /** Накопитель: помнит все вызовы и отдаёт их отчётом. */
    static CallProfiler collecting() {
        return new CallProfiler();
    }
}
