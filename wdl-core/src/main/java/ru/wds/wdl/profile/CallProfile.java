package ru.wds.wdl.profile;

import java.time.Duration;

/**
 * Итог по одному месту: сколько раз позвали и сколько это заняло.
 *
 * <h2>Всего и сам</h2>
 * Два времени, и путать их нельзя. <b>Всего</b> — от входа в вызов до выхода, вместе
 * со всем, что вызов позвал изнутри. <b>Сам</b> — то же время за вычетом вложенных
 * вызовов, то есть работа самой функции. Функция, которая только раздаёт работу
 * другим, имеет большое «всего» и почти нулевое «сам», и правит горячий код тот,
 * кто смотрит на второе.
 * <p>
 * <b>Рекурсия считается один раз.</b> Вложенный вход в ту же функцию своё «всего»
 * в сумму не добавляет: иначе {@code fib(25)} показал бы время больше времени всего
 * запуска — каждый уровень рекурсии посчитал бы одни и те же наносекунды заново.
 * На «сам» это не влияет вовсе: собственное время у каждого уровня своё.
 *
 * @param site          что вызывали и где оно объявлено
 * @param calls         сколько раз вызов случился — считая рекурсивные входы
 * @param totalNanos    время вместе с вложенными вызовами, без повторного счёта рекурсии
 * @param selfNanos     время без вложенных вызовов
 * @param maxNanos      самый долгий вызов: по нему видно разброс, которого не видно
 *                      в среднем
 */
public record CallProfile(CallSite site, long calls, long totalNanos, long selfNanos,
                          long maxNanos) {

    /** Время вместе с вложенными вызовами. */
    public Duration total() {
        return Duration.ofNanos(totalNanos);
    }

    /** Время без вложенных вызовов — работа самой функции. */
    public Duration self() {
        return Duration.ofNanos(selfNanos);
    }

    /** Самый долгий вызов. */
    public Duration max() {
        return Duration.ofNanos(maxNanos);
    }

    /** Среднее «всего» на вызов; нулевое число вызовов даёт ноль, а не деление на ноль. */
    public Duration average() {
        return calls == 0 ? Duration.ZERO : Duration.ofNanos(totalNanos / calls);
    }
}
