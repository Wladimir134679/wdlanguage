package ru.wds.wdl.profile;

import java.time.Duration;
import java.util.List;

/**
 * Профиль запуска — только на чтение.
 * <p>
 * Отдельным интерфейсом от {@link Profiler} по той же причине, по которой
 * {@code MetricsReport} отделён от {@code Metrics}: право писать вызовы и право читать
 * итог — разные права. Приложению нужен отчёт, а не объект, в который можно дописать
 * чужой вызов.
 *
 * <h2>Почему сумма «всего» не равна времени по часам</h2>
 * Причины те же две, что и у метрик, и обе — свойства языка, а не измерения.
 * <b>Вложенность</b>: время функции входит во время того, кто её позвал, и складывать
 * их нельзя — для этого и есть {@linkplain CallProfile#self() «сам»}, сумма которого
 * как раз сходится. <b>Потоки</b>: внутри запуска их сколько угодно, и два вызова идут
 * одновременно.
 */
public interface ProfileReport {

    /** Все записи профиля, от самой горячей по собственному времени к холодной. */
    List<CallProfile> all();

    /** Первые {@code limit} записей того же порядка; {@code limit <= 0} — все. */
    List<CallProfile> hottest(int limit);

    /** Граф вызовов: кто кого звал. Порядок — от самого дорогого ребра. */
    List<CallEdge> edges();

    /** Сколько вызовов всего попало в профиль. */
    long calls();

    /**
     * Сумма собственного времени всех записей — то самое, что складывать можно.
     * <p>
     * Меньше времени по часам ровно на то, чего профиль не видит: разбор файлов,
     * ожидание в блокирующем вызове библиотеки, работу приложения между вызовами.
     */
    Duration self();

    /** Время по часам: от создания профиля до {@code finish()} или до этого мгновения. */
    Duration wall();

    /** Сколько разных потоков успело что-то позвать. */
    int threads();

    /** Не записано ни одного вызова — профиль был выключен или ничего не выполнялось. */
    boolean isEmpty();

    /** Готовая таблица для человека. Пустой профиль даёт пустую строку. */
    String render();
}
