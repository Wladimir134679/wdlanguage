package ru.wds.wdl.profile;

/**
 * Что именно вызвали: вид записи в профиле.
 * <p>
 * Видов ровно столько, сколько в движке <b>точек съёма</b>, — и это не совпадение:
 * профиль считает шаги скрипта там же, где их считают лимиты, и другого способа
 * попасть в него нет. Дробить мельче — например, писать каждый узел дерева — здесь
 * сознательно нельзя: это стоило бы в самой горячей точке, а ответ «во что ушло время»
 * даёт уже вызов.
 */
public enum CallKind {

    /**
     * Верхний уровень файла: главного скрипта или модуля.
     * <p>
     * Корень профиля, а не строка ради симметрии: без него собственное время верхнего
     * уровня («сам скрипт складывал массив в цикле») не отличалось бы от времени
     * функций, которые он позвал.
     */
    SCRIPT("файл"),

    /** Функция на wdl — обычная, вложенная, метод класса и аксессор свойства. */
    FUNCTION("функция"),

    /** Создание экземпляра: заголовок, поля, конструктор. */
    CONSTRUCTOR("создание"),

    /**
     * Написанное не на wdl: встроенная функция, метод значения ({@code a.sort()}),
     * функция библиотеки, метод за мостом в Java.
     * <p>
     * Одним видом на всё чужое, потому что различие между ними — устройство движка,
     * а не свойство скрипта: автору важно, что время ушло за границу его кода.
     */
    NATIVE("встроенное");

    private final String title;

    CallKind(String title) {
        this.title = title;
    }

    /** Название по-русски — для вывода человеку. */
    public String title() {
        return title;
    }
}
