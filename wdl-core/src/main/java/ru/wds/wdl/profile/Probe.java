package ru.wds.wdl.profile;

/**
 * Открытый счёт вызова: закрывается там, где вызов кончился.
 * <p>
 * Наследует {@link AutoCloseable}, но {@code close()} переопределён без {@code throws}
 * — по той же причине, что и у {@code metrics.Measure}: тело вызова исключения
 * не бросает, а {@code catch} вокруг закрытия пришлось бы писать в каждой точке съёма.
 * <p>
 * Закрывается из {@code finally}, а не {@code try}-с-ресурсами: сборка идёт
 * с {@code -Xlint:all}, где не читаемый в теле ресурс — законное предупреждение.
 * Из {@code finally} — ещё и затем, чтобы вызов, кончившийся ошибкой, попал в профиль:
 * время до падения тоже ответ, а функция, которая всегда бросает, обязана быть видна.
 */
public interface Probe extends AutoCloseable {

    @Override
    void close();

    /** Заглушка: закрывать её можно сколько угодно, она ничего не считает. */
    static Probe off() {
        return NoProfiler.INSTANCE;
    }
}
