package ru.wds.wdl.debug;

/**
 * Чего ждёт возобновлённый поток: просто работы или следующей остановки.
 * <p>
 * Шаг — <b>свойство потока</b>, а не сессии: в скрипте с {@code th.spawn} «шаг через
 * строку» в одном потоке не должен означать «шаг во всех восьми». Поэтому режим лежит
 * в состоянии потока и снимается той же остановкой, которую он вызвал.
 * <p>
 * Различаются режимы глубиной кадра — той самой, что {@code Frame.depth()} считает
 * один раз при создании и которую отдаёт {@code ExecutionContext.callDepth()}.
 * Второго счётчика ради шага не заводится.
 */
public enum StepMode {

    /** Просто работать до следующей точки останова или до просьбы встать. */
    RUN,

    /**
     * Встать на следующем шаге любой глубины: вход в вызванную функцию считается.
     */
    INTO,

    /**
     * Встать на следующем шаге глубины не больше нынешней: вызов проходится целиком.
     */
    OVER,

    /**
     * Встать на первом шаге глубины строго меньше нынешней: выход из текущей функции.
     */
    OUT
}
