package ru.wds.wdl.debug;

/**
 * Кого останавливать, когда сработала точка останова.
 * <p>
 * По умолчанию {@link #ALL} — то же умолчание, что у JDWP, и по той же причине:
 * состояние скрипта общее, и рассматривать его, пока соседний поток его меняет,
 * бессмысленно.
 * <p>
 * {@link #THREAD} нужен там, где остановка всех означала бы остановку приложения:
 * скрипт, живущий в игровом цикле или в обработчике событий {@code sys.gui}.
 * Он же — выход из взаимной блокировки, описанной в {@code docs/debugging.md}:
 * поток, вставший внутри {@code synchronized def}, продолжает держать замок,
 * и остальным до своего шага не добраться.
 */
public enum SuspendPolicy {

    /** Встают все потоки запуска — каждый на своём ближайшем шаге. */
    ALL,

    /** Встаёт только тот поток, у которого сработала точка. */
    THREAD
}
