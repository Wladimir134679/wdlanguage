package ru.wds.wdl.debug;

/**
 * Кому сессия рассказывает о событиях: адаптеру протокола, тесту, консоли.
 * <p>
 * Зовётся <b>из потока скрипта</b>, который в этот момент уже стоит, — и это налагает
 * на слушателя одно обязательство: не ходить обратно в сессию за тем, что требует
 * возобновления. Возобновить поток из его же обработчика можно (сессия к этому готова),
 * а вот ждать в нём другого потока скрипта — верный способ получить взаимную
 * блокировку. Правило простое: обработчик должен быть коротким и, если работа
 * долгая, откладывать её на свой поток.
 */
public interface DebugListener {

    /** Поток встал. */
    void suspended(SuspendedEvent event);

    /**
     * Поток пошёл дальше.
     * <p>
     * Отдельным событием, а не молчанием: отладчику надо погасить подсветку строки,
     * и узнать об этом иначе, чем от сессии, он не может — возобновить поток мог
     * не он (например, {@code detach} отпускает всех).
     *
     * @param threadId идентификатор потока
     */
    void resumed(long threadId);

    /** Никого не слушает: значение по умолчанию у сессии. */
    static DebugListener none() {
        return new DebugListener() {
            @Override
            public void suspended(SuspendedEvent event) {
            }

            @Override
            public void resumed(long threadId) {
            }
        };
    }
}
