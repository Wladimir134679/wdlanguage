package ru.wds.wdl.debug;

import ru.wds.wdl.ast.stmt.Stmt;
import ru.wds.wdl.runtime.ExecutionContext;
import ru.wds.wdl.runtime.WdlRuntimeError;
import ru.wds.wdl.source.Span;

/**
 * Куда движок сообщает о шагах скрипта: приёмник отладки.
 * <p>
 * Отладчик — <b>зависимость, а не статика</b>, ровно как {@code Metrics},
 * {@code Profiler} и {@code Output}: его создаёт хозяин запуска и передаёт в контекст.
 * Сессия в статическом поле сложила бы вместе два интерпретатора, работающих
 * в одном процессе, — а движок обещает обратное.
 *
 * <h2>Три точки съёма, и все там, где скрипт делает шаг</h2>
 * <ul>
 *   <li>{@link #at(Stmt, ExecutionContext)} — перед выполнением инструкции. Это
 *       и есть «остановка на строке»: у инструкции есть {@code Span}, и он же
 *       служит ключом точки останова;</li>
 *   <li>{@link #poll(Span)} — там, где шаг есть, а инструкции нет: итерация цикла,
 *       вызов функции, создание экземпляра. Зовётся из {@code Run.checkpoint},
 *       рядом с проверкой пределов;</li>
 *   <li>{@link #failed(WdlRuntimeError)} — инструкция кончилась ошибкой. Зовётся
 *       из того же {@code Interpreter.step}, с той же стороны, что и {@link #at}.</li>
 * </ul>
 * Вторая точка не роскошь: тело функции бывает выражением
 * ({@code def f(n) => n <= 1 ? 1 : f(n - 1) + f(n - 2)}), и в таком скрипте
 * инструкций не выполняется вовсе — без {@code poll} он не встал бы никогда.
 *
 * <h2>Выключённая отладка стоит чтение поля и сравнение</h2>
 * Правило то же, что у {@code Limits.counting()} и {@code Profiler.recording()},
 * только флаг здесь плоский: {@code Run.debugging()} — {@code volatile boolean},
 * и на выключенном пути JIT сворачивает ветку целиком. Ни таблицы точек, ни стека
 * кадров, ни снимка окружения на обычном пути не существует.
 * <pre>{@code
 * Run run = context.run();
 * if (run.debugging()) {
 *     run.debugger().at(stmt, context);
 * }
 * return visit(stmt, context);
 * }</pre>
 *
 * <h2>Почему не пометки в дереве</h2>
 * HotSpot ставит точку останова, подменяя байткод, и потому не отлаживаемый код
 * не платит ничего. Так здесь нельзя: дерево неизменяемо и <b>делится между
 * запусками и потоками</b> — точка, поставленная в одном запуске, останавливала бы
 * другой. Отсюда таблица точек у сессии и проверка на шаге.
 */
public interface Debugger {

    /**
     * Скрипт дошёл до инструкции и ещё не выполнил её.
     *
     * @param stmt    инструкция, которая сейчас будет выполнена
     * @param context место выполнения: область видимости, файл, кадр вызова
     */
    void at(Stmt stmt, ExecutionContext context);

    /**
     * Точка шага без инструкции: итерация цикла, вызов, создание экземпляра.
     * <p>
     * Контекста здесь нет намеренно — {@code Run.checkpoint} его не получает,
     * и протаскивать его через все точки проверки пределов значило бы платить
     * за отладку в местах, где её обычно нет. Сессии хватает того, что она уже
     * знает про поток из предыдущего {@link #at}.
     *
     * @param span место, которому принадлежит шаг
     */
    void poll(Span span);

    /**
     * Выполнение инструкции кончилось ошибкой, и она ещё не улетела наружу.
     *
     * <h2>Почему одна точка, а не две</h2>
     * Ошибка скрипта родится в трёх разных местах: её бросает сам скрипт
     * ({@code throw}), её бросает движок (неверный тип, деление на ноль, выход
     * за границы) и её приносит чужой код ({@code Foreign.call}, {@code ErrorKind.JAVA}).
     * Ставить точку съёма в каждом значило бы разложить одно правило по трём местам —
     * ровно то, чем плохо было правило «что своё, что чужое» до появления
     * {@code Foreign}. К тому же до {@code Foreign} отсюда не дотянуться: он статический
     * и запуска не знает, а тащить {@code Run} через семь его вызовов — плата
     * за отладку в местах, где её обычно нет.
     * <p>
     * Поэтому точка одна и стоит там же, где {@link #at}: на выходе из инструкции.
     * Ошибка, откуда бы она ни шла, обязана пройти через инструкцию, внутри которой
     * случилась.
     *
     * <h2>Останов — до раскрутки</h2>
     * Инструкции вложены, и одна ошибка пройдёт через всю их цепочку наружу. Сообщается
     * о ней <b>каждый раз</b>, а отбирает первое сообщение приёмник: первым будет
     * самое глубокое место — то, где ошибка и случилась, — и кадры в этот момент ещё
     * целы. Отличить «та же ошибка» от новой по тождеству объекта нельзя — граница
     * функции пересоздаёт ошибку, дописывая ей файл, — зато известно, что между двумя
     * сообщениями об одной ошибке поток не делает ни шага.
     * <p>
     * {@code FatalError} сюда не приходит вовсе: исчерпание шагов, вышедшее время
     * и остановка выполнения — это конец запуска, а не ошибка, которую разглядывают
     * в отладчике.
     *
     * @param error ошибка, которая сейчас полетит наружу
     */
    void failed(WdlRuntimeError error);

    /** Ничего не знает и никого не останавливает — значение по умолчанию у запуска. */
    static Debugger off() {
        return NoDebugger.INSTANCE;
    }
}
