package ru.wds.wdl.lexer;

/**
 * Что лексер кладёт в поток кроме значимых токенов.
 * <p>
 * Два режима, а не два лексера: правила языка одни, и разойтись двум их копиям
 * не с чем — они бы разошлись на первой же правке грамматики. Разница ровно в том,
 * попадают ли в список пробелы, комментарии и мусор.
 * <p>
 * Флаг, а не постоянная выдача тривии с фильтром в парсере, — потому что цена разная:
 * скрипт лексится на каждом запуске, а подсветка живёт в редакторе, где лишний список
 * токенов ничего не стоит рядом с самим редактированием.
 */
public enum LexerMode {

    /**
     * Только то, что нужно разбору. Поток такой же, каким он был до появления тривии:
     * пробелы и комментарии пропущены, неизвестный символ ушёл в
     * {@link ru.wds.wdl.diagnostic.Diagnostics} и токена не оставил.
     */
    RUNTIME,

    /**
     * Всё, что есть в документе: {@link TokenType#WHITESPACE},
     * {@link TokenType#LINE_COMMENT}, {@link TokenType#BLOCK_COMMENT} и
     * {@link TokenType#BAD_CHARACTER} идут в поток наравне со значимыми токенами.
     * <p>
     * Гарантия режима — <b>поток покрывает документ встык</b>: интервалы идут подряд
     * от нуля до конца текста, без дыр и пересечений, последним стоит {@code EOF}
     * нулевой длины. Ровно этого требует лексер подсветки IntelliJ и {@code semanticTokens}
     * в LSP; дыра для них — либо исключение, либо пропавший кусок файла.
     * <p>
     * Значимые токены в этом режиме те же самые и с теми же интервалами, что
     * и в {@link #RUNTIME}, — это закреплено тестом.
     */
    LOSSLESS
}
