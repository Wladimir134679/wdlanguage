package ru.wds.wdl.lexer;

/**
 * Вид токена.
 * <p>
 * Ключевые слова и операторы несут здесь же свою лексему — таблицы для лексера
 * строятся из этого перечисления, а не пишутся рядом вторым списком. Забыть добавить
 * оператор в таблицу невозможно: он либо объявлен здесь, либо не существует.
 */
public enum TokenType {

    // --- имена и литералы ---------------------------------------------------
    /** Идентификатор: имя переменной, функции, поля. */
    WORD(Kind.VALUE),
    /** Целое десятичное число. Текст токена — цифры без разделителей {@code _}. */
    INT(Kind.VALUE),
    /** Дробное число или число с экспонентой. */
    FLOAT(Kind.VALUE),
    /** Шестнадцатеричное число. Текст токена — цифры без префикса {@code 0x}. */
    HEX(Kind.VALUE),
    /** Двоичное число. Текст токена — цифры без префикса {@code 0b}. */
    BIN(Kind.VALUE),
    /** Строковый литерал. Текст токена — уже развёрнутое значение, без кавычек. */
    STRING(Kind.VALUE),
    /**
     * Пропуск: одиночное {@code _} в списке параметров, в целях распаковки
     * и в переменных {@code for}.
     * <p>
     * <b>Отдельный вид токена, а не имя со специальным значением.</b> Будь это
     * {@link #WORD} с текстом {@code "_"}, каждое место, куда пропуск нельзя —
     * позиция выражения, ключ объекта, обращение {@code a._}, — обязано было бы
     * сравнивать строку и помнить об этом сравнении. Здесь же пропуск не попадает
     * туда, где ждут имя, просто потому, что он не {@code WORD}.
     * <p>
     * Ровно один символ подчёркивания: {@code _x}, {@code __}, {@code _1} —
     * обычные имена, и {@link #WORD} им остаётся.
     */
    HOLE(Kind.VALUE, "_"),

    // --- ключевые слова -----------------------------------------------------
    /** Имя, которое нельзя переприсвоить: {@code const LIMIT = 10}. */
    CONST("const"),
    DEF("def"),
    /**
     * Модификатор функции: вызовы одной такой функции не идут одновременно.
     * У метода класса замок — экземпляр, а не метод. См. {@code docs/threads.md}.
     */
    SYNCHRONIZED("synchronized"),
    RETURN("return"),
    IF("if"),
    ELSE("else"),
    WHILE("while"),
    DO("do"),
    FOR("for"),
    /**
     * Два применения одного слова.
     * <p>
     * Перебор: {@code for (item in cart)} — отдельного {@code foreach} в языке нет.
     * И обычный бинарный оператор принадлежности: {@code role in user.roles}.
     * Форму перебора парсер узнаёт по двум токенам после скобки, до общего разбора
     * выражения, — см. {@code Parser.forStatement}.
     */
    IN("in"),
    BREAK("break"),
    CONTINUE("continue"),
    /** Бросок ошибки: {@code throw new ParseError(text)}. */
    THROW("throw"),
    TRY("try"),
    /** Обработчик: {@code catch (e is IoError, ValueError)}. Тип после {@code is} — имя. */
    CATCH("catch"),
    /** Блок, который выполняется при любом выходе из {@code try}. */
    FINALLY("finally"),
    /** Отложенное действие: {@code defer file.close()}. Область — блок, а не функция. */
    DEFER("defer"),
    /** Работа с ресурсом: {@code use (f = io.open(path)) { ... }}. */
    USE("use"),
    MATCH("match"),
    CASE("case"),
    /**
     * Отдать значение из ветки {@code case}: {@code yield price * count}.
     * <p>
     * Слово, а не «последнее выражение блока — результат». Неявный результат
     * читатель обязан вычислить сам, пробежав блок до конца и вспомнив правило;
     * ошибиться в этом легко, а видно ошибку не будет. {@code yield} стоит там,
     * где значение отдают, и его нельзя не заметить.
     */
    YIELD("yield"),
    CLASS("class"),
    /** Трейт: класс, у которого забрали конструктор. Заменяет и {@code interface}, и {@code abstract}. */
    TRAIT("trait"),
    NEW("new"),
    THIS("this"),
    /** Тот же экземпляр, но поиск методов начинается с родителя. */
    SUPER("super"),
    /** Подмешивание трейтов: {@code class Basket(items) with Printable, Counted}. */
    WITH("with"),
    /** Проверка класса или трейта: {@code figure is Circle}. Обычный бинарный оператор. */
    IS("is"),
    /**
     * Принадлежность, записанная от контейнера: {@code roles has "admin"}.
     * <p>
     * Зеркало {@link #IN} с той же реализацией. Второе имя существует не ради
     * синонима: в {@code match} левый операнд зафиксирован предметом, и фразу
     * «предмет содержит "admin"» иначе не записать.
     */
    HAS("has"),
    IMPORT("import"),
    AS("as"),
    TRUE("true"),
    FALSE("false"),
    NULL("null"),

    // --- скобки и знаки препинания ------------------------------------------
    LPAREN("("),
    RPAREN(")"),
    LBRACE("{"),
    RBRACE("}"),
    LBRACKET("["),
    RBRACKET("]"),
    COMMA(","),
    DOT("."),
    /**
     * Диапазон: {@code 1..5}. Границы включительны с обеих сторон.
     * <p>
     * Числа от него не страдают по построению: {@code number()} берёт точку, только
     * когда за ней цифра, поэтому {@code 1..5} — это {@code INT}, {@code ..},
     * {@code INT}, а {@code 1.5..3} разбирается так же без единого исключения.
     */
    DOTDOT(".."),
    COLON(":"),
    QUESTION("?"),
    ARROW("->"),
    /** Тело-выражение функции: {@code def f(a, b) => a + b}. Заменяет {@code return}. */
    FATARROW("=>"),
    /** Необязательный разделитель инструкций. Обязателен там, где его требует синтаксис: {@code for (i = 0; i < n; i++)}. */
    SEMICOLON(";"),
    /**
     * Начало декоратора: {@code @[log]("info")}.
     * <p>
     * Дальше всегда идёт {@code [}, и это не украшение: без скобок {@code @t.deco()}
     * неразличимо — то ли декоратор {@code deco} без аргументов, то ли вызов, чей
     * результат станет декоратором. Скобки разводят эти два написания, и в них лежит
     * обычное выражение. См. {@code docs/decorators.md}.
     */
    AT("@"),

    // --- арифметика ---------------------------------------------------------
    PLUS("+"),
    MINUS("-"),
    STAR("*"),
    /** Остаток по именам в заголовке и раскрытие объекта в вызове: {@code **named}. */
    STARSTAR("**"),
    SLASH("/"),
    PERCENT("%"),
    PLUSPLUS("++"),
    MINUSMINUS("--"),

    // --- сравнение ----------------------------------------------------------
    EQ("=="),
    NOTEQ("!="),
    LT("<"),
    GT(">"),
    LTEQ("<="),
    GTEQ(">="),

    // --- логика -------------------------------------------------------------
    ANDAND("&&"),
    OROR("||"),
    NOT("!"),

    // --- биты ---------------------------------------------------------------
    AMP("&"),
    BAR("|"),
    CARET("^"),
    TILDE("~"),
    SHL("<<"),
    SHR(">>"),
    USHR(">>>"),

    // --- присваивания -------------------------------------------------------
    ASSIGN("="),
    PLUSASSIGN("+="),
    MINUSASSIGN("-="),
    STARASSIGN("*="),
    SLASHASSIGN("/="),
    PERCENTASSIGN("%="),
    AMPASSIGN("&="),
    BARASSIGN("|="),
    CARETASSIGN("^="),
    SHLASSIGN("<<="),
    SHRASSIGN(">>="),
    USHRASSIGN(">>>="),

    // --- служебные ----------------------------------------------------------
    /** Конец файла. Всегда последний токен потока. */
    EOF(Kind.SERVICE);

    private enum Kind { VALUE, KEYWORD, OPERATOR, SERVICE }

    private final Kind kind;
    private final String text;

    TokenType(Kind kind) {
        this.kind = kind;
        this.text = "";
    }

    /**
     * Вид с фиксированным написанием, но не ключевое слово и не оператор:
     * {@linkplain #HOLE пропуск}. Написание нужно диагностике, а вид — тому,
     * что таблицы лексера собираются по {@link #isKeyword()} и {@link #isOperator()}
     * и лишнего в них не берут.
     */
    TokenType(Kind kind, String text) {
        this.kind = kind;
        this.text = text;
    }

    /** Ключевое слово, если лексема состоит из букв, иначе оператор. */
    TokenType(String text) {
        this.kind = Character.isLetter(text.charAt(0)) ? Kind.KEYWORD : Kind.OPERATOR;
        this.text = text;
    }

    /** Лексема токена с фиксированным написанием; для имён и литералов — пустая строка. */
    public String text() {
        return text;
    }

    public boolean isKeyword() {
        return kind == Kind.KEYWORD;
    }

    public boolean isOperator() {
        return kind == Kind.OPERATOR;
    }

    /** Число любой системы счисления. */
    public boolean isNumber() {
        return this == INT || this == FLOAT || this == HEX || this == BIN;
    }

    /** Как назвать токен в сообщении об ошибке. */
    public String describe() {
        return text.isEmpty() ? name() : "'" + text + "'";
    }
}
