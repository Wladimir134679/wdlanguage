package ru.wds.wdl.metrics;

/**
 * Стадия конвейера, время которой измеряется.
 * <p>
 * Стадий ровно столько, сколько их в самом конвейере {@code Source → Lexer → Parser →
 * Interpreter}, плюс закрытие запуска. Дробить мельче — например, считать каждый вызов
 * функции — здесь сознательно нельзя: это профилировщик, у него другая цена и другой
 * способ включения. Метрики отвечают на вопрос «во что ушло время запуска», а не
 * «какая функция скрипта самая горячая».
 */
public enum Stage {

    /** Текст → токены. */
    LEX("лексер"),
    /** Токены → дерево. */
    PARSE("парсер"),
    /**
     * Выполнение файла целиком — главного скрипта или модуля.
     * <p>
     * Меряется верхний уровень файла, а не каждый вход в скрипт: вызов функции скрипта
     * из приложения — это тоже вход, и считать его стадией конвейера значило бы
     * складывать несравнимое.
     */
    EXECUTE("выполнение"),
    /**
     * Закрытие запуска: остановка потоков скрипта и закрытие библиотек.
     * <p>
     * Отдельной стадией, потому что это настоящее время запуска и иногда основное:
     * {@code sys.gui} в {@code close()} ждёт, пока пользователь закроет окна.
     */
    SHUTDOWN("закрытие");

    private final String title;

    Stage(String title) {
        this.title = title;
    }

    /** Название по-русски — для вывода человеку. */
    public String title() {
        return title;
    }
}
