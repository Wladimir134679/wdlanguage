package ru.wds.wdl.metrics;

import java.time.Duration;
import java.util.List;
import java.util.Map;

/**
 * Отчёт о времени стадий — только на чтение.
 * <p>
 * Отдельным интерфейсом от {@link Metrics}, потому что право писать замеры и право
 * их читать — разные права: конвейеру нужен приёмник, приложению — отчёт, и отдавать
 * наружу объект, в который можно дописать чужой замер, незачем.
 *
 * <h2>Почему сумма замеров не равна времени по часам</h2>
 * Две независимые причины, и обе — свойства языка, а не измерения.
 * <ul>
 *   <li><b>Потоки.</b> Внутри запуска их сколько угодно, и два {@code EXECUTE} идут
 *       одновременно: сумма их времён больше прошедшего. См. {@code docs/threads.md};</li>
 *   <li><b>Вложенность.</b> {@code import} выполняется внутри {@code EXECUTE} главного
 *       файла, поэтому время модуля входит во время скрипта и во «всём вместе»
 *       посчиталось бы дважды.</li>
 * </ul>
 * Поэтому здесь два разных числа — {@link #sum()} и {@link #wall()} — и в выводе они
 * подписаны по-разному. Одно «итого» врало бы ровно на многопоточном скрипте с модулями,
 * то есть там, где метрики и нужны.
 */
public interface MetricsReport {

    /** Все замеры в порядке завершения. */
    List<Measurement> all();

    /** Сумма времён по каждой стадии — вместе с модулями. */
    Map<Stage, Duration> byStage();

    /** Сумма времён стадии: и главный файл, и модули. */
    Duration total(Stage stage);

    /** Сумма времён стадии отдельно по главному файлу ({@code false}) и модулям. */
    Duration total(Stage stage, boolean module);

    /** Сколько раз стадия отработала: и главный файл, и модули. */
    int count(Stage stage);

    /** Сколько раз стадия отработала отдельно по главному файлу и по модулям. */
    int count(Stage stage, boolean module);

    /** Сумма всех замеров. Не «время запуска» — см. javadoc интерфейса. */
    Duration sum();

    /**
     * Время по часам: от создания накопителя до {@code finish()}, а если его ещё
     * не звали — до этого мгновения.
     */
    Duration wall();

    /** Сколько разных потоков успело что-то намерить. */
    int threads();

    /** Не сделано ни одного замера — метрики были выключены или ничего не запускалось. */
    boolean isEmpty();

    /** Готовая таблица для человека. Пустой отчёт даёт пустую строку. */
    String render();
}
