/**
 * Синтаксический анализ: поток токенов → AST.
 * <p>
 * Рукописный рекурсивный спуск для инструкций и Pratt-парсер (precedence climbing)
 * для выражений: приоритеты операторов задаются таблицей, а не лестницей методов.
 * Генераторы парсеров сознательно не используются — синтаксис языка допускает
 * необязательные фигурные скобки и не требует разделителей инструкций, что плохо
 * ложится на декларативные грамматики.
 * <p>
 * Наружу смотрит один {@link ru.wds.wdl.parser.Parser}, остальное — внутренности
 * пакета. Разложены они по зависимостям, а не по конструкциям языка: инструкции
 * и выражения связаны взаимной рекурсией (тело {@code if} — инструкция, инструкция
 * бывает выражением, выражение бывает функцией с телом) и потому лежат вместе,
 * а отдельными файлами вынесено то, что в это кольцо не входит.
 * <ul>
 *   <li>{@link ru.wds.wdl.parser.Parser} — инструкции, выражения, точки входа;</li>
 *   <li>{@link ru.wds.wdl.parser.TypeParser} — объявления классов и трейтов,
 *       их тела и списки параметров;</li>
 *   <li>{@link ru.wds.wdl.parser.TokenCursor} — курсор по потоку токенов и
 *       восстановление после ошибки;</li>
 *   <li>{@link ru.wds.wdl.parser.ParseState} — где мы находимся (цикл, функция,
 *       {@code finally}, тело класса) и что здесь запрещено;</li>
 *   <li>{@link ru.wds.wdl.parser.Operators} — таблица приоритетов;</li>
 *   <li>{@link ru.wds.wdl.parser.DefaultValues} и
 *       {@link ru.wds.wdl.parser.NumberLiterals} — проверки и вычисления,
 *       которым поток токенов уже не нужен.</li>
 * </ul>
 */
