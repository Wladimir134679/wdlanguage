package ru.wds.wdl.value;

/**
 * Член значения: ответ на обращение по имени там, где собственных данных с таким
 * ключом у значения нет.
 * <p>
 * <b>Ни нового узла, ни новой формы записи.</b> {@code text.size} — это
 * {@code text["size"]}, и правило {@code x.имя ≡ x["имя"]} остаётся дословно верным;
 * член лишь отвечает на тот же вопрос, когда данных не нашлось. Отсюда и то, что
 * в других языках приходится делать отдельно: имя члена можно вычислить
 * ({@code value[name]} в цикле), а метод — обычное значение, которое читается
 * в переменную и вызывается позже.
 * <p>
 * <b>Половины две, и различать их обязано само объявление.</b> Свойство читается
 * без скобок, метод — со скобками, и молча возвращать функцию там, где автор ждал
 * значение, нельзя. Граница между ними — не «дорого или дёшево», а можно ли верить
 * ответу через строку:
 * <ul>
 *   <li><b>свойство</b> — ответ зависит только от значения, каким оно видно сейчас,
 *       и измениться может лишь от действия, написанного в тексте;</li>
 *   <li><b>метод</b> — есть аргументы, или меняется получатель, или ответ приходит
 *       из времени либо из мира снаружи, или честное имя для него — глагол.</li>
 * </ul>
 * Планка выбрана именно эта — «не меняется само по себе», а не «не меняется
 * никогда», — потому что более высокую язык не держит и в основании: {@code a[0]}
 * после записи в массив тоже отвечает иначе, и никто не считает это ложью.
 * <p>
 * <b>Цена объявляется членом, а не выводится из имени.</b> {@link #snapshot()} —
 * это то, из чего линтер вправе сказать «член собирает новый массив на каждое
 * чтение, вынесите его из цикла», а по имени о чужом члене не узнать ничего.
 * Свойством-снимком член от этого быть не перестаёт: цена — вторая ось, а не вторая
 * граница.
 *
 * @see MemberSet набор членов одного типа или класса
 */
public interface Member {

    String name();

    /**
     * Свойство или {@code null}, если это метод.
     * <p>
     * Протокол здесь тот же {@link Property}, что у свойства класса, и это не
     * экономия на классе: правила чтения, записи и невидимости в переборе одни
     * и те же, а второе понятие «свойство» с другими правилами развело бы класс
     * и тип по разным механизмам.
     */
    Property property();

    /**
     * Метод, связанный с получателем, или {@code null}, если это свойство.
     * <p>
     * Связывание — тот же приём, что у метода класса: получатель уходит в замыкание,
     * поэтому {@code push = a.push} не теряет массив.
     */
    FunctionValue bind(Value receiver);

    /**
     * Сколько аргументов принимает метод; у свойства — ноль.
     * <p>
     * Спрашивается до получателя: дескриптору типа надо объявить арность функции
     * {@code Array.push(a, value)}, когда никакого массива ещё нет.
     */
    Arity arity();

    /** Собирает ли член новое значение за {@code O(n)} на каждое чтение. */
    boolean snapshot();

    default boolean isProperty() {
        return property() != null;
    }
}
