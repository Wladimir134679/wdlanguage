package ru.wds.wdl.value;

/**
 * Связка: имя, заведённое здесь, а живущее в другом месте.
 * <p>
 * Нужна ровно одному — развёрнутому импорту. {@code import lib.math} обещает, что
 * имена модуля ведут себя так же, как если бы их объявили в этом файле, а модуль
 * выполняется один раз за запуск и значение у всех импортёров общее. Копия значения
 * эти два обещания сдержать не может: присваивание {@code PI = 4} поменяло бы копию,
 * функции модуля продолжили бы считать по-старому, а второй импортёр не увидел бы
 * ничего. Поэтому имя не копируется, а связывается — и обе стороны смотрят в одну
 * ячейку.
 * <p>
 * <b>Почему здесь, а не в {@code runtime}.</b> Связку обязан понимать
 * {@link ru.wds.wdl.value.types.ModuleValue}: имена, пришедшие в модуль развёрнутым
 * импортом, уходят наружу вместе с его собственными, и спрашивают их через него.
 * Пакет {@code value} про {@code runtime} не знает ничего — и не должен узнать
 * ради одного интерфейса из трёх методов.
 */
public interface Binding {

    /** Текущее значение имени. */
    Value value();

    /** Заморожено ли имя там, где живёт: {@code const} остаётся {@code const} и здесь. */
    boolean constant();

    /**
     * Записывает значение туда, где имя живёт.
     *
     * @return {@code false}, если имя заморожено {@code const}, — записи не было.
     *         Отказ возвращается, а не бросается: у связки нет места в исходнике,
     *         а диагностика без места бесполезна. Решение принимает тот, кто знает,
     *         откуда пришло присваивание
     */
    boolean set(Value value);
}
