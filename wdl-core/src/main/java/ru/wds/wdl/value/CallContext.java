package ru.wds.wdl.value;

/**
 * То, что функция получает от выполняющей её среды.
 * <p>
 * Встроенной функции почти всегда мало одних аргументов: {@code println} нужно знать,
 * куда писать, будущей {@code time()} — часы, а функциям высшего порядка вроде
 * {@code map} — способ вызвать переданную им функцию. Всё это приходит сюда, а не
 * оседает в полях самой функции: тогда одно и то же значение-функция работает
 * в любом количестве независимых интерпретаторов, а вывод скрипта можно перенаправить
 * в лог, в строку или в никуда, ничего в ядре не трогая.
 * <p>
 * Интерфейс объявлен здесь, а не в {@code runtime}, чтобы значения не зависели
 * от того, кто их выполняет: реализует его {@code ExecutionContext}.
 */
public interface CallContext {

    /** Вывод скрипта: сюда пишут {@code print} и {@code println}. */
    void write(String text);

    /**
     * Сколько вызовов функций уже в работе — глубина стека выполнения скрипта.
     * <p>
     * Нужна пользовательской функции, чтобы поймать бесконечную рекурсию ошибкой
     * скрипта, а не {@code StackOverflowError} в чужом приложении. Значение по умолчанию
     * позволяет реализовать этот интерфейс одной лямбдой там, где до вызовов дела нет —
     * например в тесте, собирающем вывод в строку.
     */
    default int callDepth() {
        return 0;
    }

    /**
     * Реестр потоков запуска: через него библиотека заводит поток, а не через
     * {@code new Thread}.
     * <p>
     * Причина — в {@link ScriptThreads}: запуск обязан уметь остановить то, что
     * породил, а поток, о котором он не знает, переживает закрытие и работает
     * по закрытым ресурсам. Значение по умолчанию оставляет интерфейс реализуемым
     * одной лямбдой там, где запуска нет вовсе.
     */
    default ScriptThreads threads() {
        return ScriptThreads.unmanaged();
    }

    /**
     * Члены, добавленные запуску: {@code extend} и установленное приложением.
     * <p>
     * Нужны там, где значение спрашивают об операторе, — сортировке массива,
     * члену {@code contains}, самому интерпретатору. Значение по умолчанию оставляет
     * интерфейс реализуемым одной лямбдой: контекст без запуска ничего не добавлял,
     * и искать в нём нечего.
     */
    default MemberLookup members() {
        return MemberLookup.none();
    }
}
