package ru.wds.wdl.value;

import ru.wds.wdl.source.Span;
import ru.wds.wdl.value.types.InstanceObjectValue;

/**
 * Свойство класса: имя, за которым стоит код, а не ячейка.
 * <p>
 * Читается и пишется тем же обращением, что поле — {@code r.area} и {@code r["area"]}
 * одинаково зовут {@link #read}, — но между обращением и значением встаёт вызов.
 * Отсюда всё, чем свойство отличается от поля:
 * <ul>
 *   <li>перебором и {@code len} его не видно: среди пар экземпляра его нет;</li>
 *   <li>запись при {@code writable() == false} — ошибка, а не заведение нового поля;</li>
 *   <li>обещание «одно обращение атомарно» на него не распространяется: вызов
 *       целиком не атомарен, и {@code w.width += 1} из двух потоков теряет обновление
 *       там, где обычное поле его не теряло бы.</li>
 * </ul>
 * <b>Реализаций две, и интерпретатор их не различает</b> — тот же приём, что
 * у {@link ClassValue} и {@link FunctionValue}: свойство, написанное на wdl, знает
 * про дерево и замыкание; свойство от приложения — про Java-лямбды.
 * <p>
 * Значение отдаётся, а не место: {@code x = window.width} кладёт в {@code x} число,
 * и передать «саму ячейку» нельзя — ссылок в языке нет вовсе. Кому нужно поведение,
 * передаёт функции: {@code def () => window.width}.
 */
public interface Property {

    String name();

    /** Объявлено ли чтение. У свойства класса всегда да — иначе оно не заводится. */
    boolean readable();

    /** Объявлена ли запись: свойство только для чтения отвечает {@code false}. */
    boolean writable();

    /**
     * Читает: зовёт getter по этому экземпляру.
     * <p>
     * Приёмником служит сам объект, а не вид {@code super}, через который свойство
     * могли прочитать, — по той же причине и тем же правилом, что у метода.
     */
    Value read(InstanceObjectValue instance, CallContext context, Span span);

    /**
     * Пишет: зовёт setter.
     * <p>
     * Зовущий обязан проверить {@link #writable()} до входа сюда — чтобы сообщение
     * «только для чтения» было одинаковым у свойства на wdl и у свойства
     * от приложения, а само свойство начиналось с дела, а не с проверок. Правило
     * то же, что у проверки числа аргументов перед вызовом функции.
     */
    void write(InstanceObjectValue instance, Value value, CallContext context, Span span);
}
