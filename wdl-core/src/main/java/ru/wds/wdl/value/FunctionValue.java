package ru.wds.wdl.value;

import ru.wds.wdl.source.Span;

import java.util.List;

/**
 * Функция как значение.
 * <p>
 * В языке одно пространство имён: {@code println} — не синтаксис и не особая
 * сущность, а обычное значение в обычной переменной. Отсюда сразу следует всё
 * остальное: функцию можно передать аргументом, вернуть из другой функции, положить
 * в массив и в поле объекта, а вызов {@code точка.строкой()} — это обращение
 * по ключу, давшее функцию, и её вызов.
 * <p>
 * Интерфейс, а не {@code record}: реализации бывают разные — встроенная функция
 * ({@code runtime.BuiltinFunction}), позже пользовательская с телом-деревом
 * и замыканием, ещё позже мост к Java-методу. Для вызывающего они неразличимы.
 * Поэтому {@link Value} и остаётся {@code sealed}, а эта его ветка открыта.
 */
public non-sealed interface FunctionValue extends Value {

    /** Имя для диагностики и печати; у анонимной функции — что-то вроде {@code "def"}. */
    String name();

    Arity arity();

    /**
     * Имя, под которым функция известна, или {@code null}, если его нет вовсе.
     * <p>
     * Отличается от {@link #name()} ровно в одном: {@code name()} обязан вернуть строку
     * для сообщения об ошибке и у безымянной функции возвращает {@code "def"}.
     * Это подстановка для человека, а не имя, и в данные ей попадать нельзя:
     * {@code commands[meta.name] = ...} зарегистрировал бы такую функцию под ключом
     * {@code "def"}, а вторая такая же молча затёрла бы первую.
     * <p>
     * Имя цели простого присваивания сюда попадает: у {@code f = def(a) => a} оно
     * {@code "f"}. Функция при этом остаётся {@linkplain #anonymous() анонимной} —
     * это два разных вопроса, и оба нужны метаданным декоратора.
     */
    default String knownName() {
        return name();
    }

    /**
     * Объявлена ли функция без имени: {@code def(a) => a} против {@code def f(a) => a}.
     * <p>
     * По {@link #name()} этого не узнать: у анонимной там стоит имя цели присваивания,
     * если его удалось подсмотреть при разборе, или {@code "def"} — и то и другое
     * только для сообщений. Спрашивают об этом ровно в одном месте — в метаданных
     * декоратора, — и врать там нельзя: {@code f = @[reg] def(){}} и
     * {@code @[reg] def f(){}} для регистрирующего декоратора разные случаи.
     * <p>
     * По умолчанию {@code false}: функция, написанная приложением, всегда объявлена
     * под именем — иначе её нельзя было бы положить в область видимости.
     */
    default boolean anonymous() {
        return false;
    }

    /**
     * Контракт вызова: имена параметров и их обязательность.
     * <p>
     * По умолчанию — контракт без имён, выведенный из {@link #arity()}. Такую функцию
     * можно звать только позиционно, и это ровно то поведение, какое было у языка
     * до именованных аргументов. Функция, написанная приложением, продолжает работать,
     * ничего не переопределяя; имена объявляет тот, кто их знает, —
     * {@code runtime.UserFunction} из дерева, {@code runtime.BuiltinFunction}
     * из своего описания.
     */
    default Signature signature() {
        return Signature.positional(arity());
    }

    /**
     * Выполняет функцию. Число аргументов уже проверено по {@link #arity()}.
     *
     * @param context среда выполнения: вывод и всё, что понадобится дальше
     * @param arguments вычисленные аргументы
     * @param span место вызова в скрипте — чтобы ошибка внутри функции указывала на него
     */
    Value call(CallContext context, List<Value> arguments, Span span);

    /**
     * Выполняет функцию по разложенным аргументам — тот же вызов, но с ответом
     * на вопрос «эта позиция пропущена?».
     * <p>
     * Переопределять его нужно только тому, у кого значение по умолчанию
     * {@linkplain Signature.Param#lazy(String) отложенное}: пропуск доживает до вызова
     * лишь в этом случае. Всем остальным пропуск не достаётся вовсе — связыватель
     * подставляет готовые значения и обрезает хвост, — поэтому здесь достаточно
     * свести набор к обычному списку.
     */
    default Value call(CallContext context, Arguments arguments, Span span) {
        return call(context, arguments.asList(), span);
    }

    @Override
    default ValueType type() {
        return ValueType.FUNCTION;
    }

    /**
     * Печатается коротко — {@code def println}. Сколько функция берёт аргументов,
     * человек узнаёт в тот момент, когда это важно: из сообщения об ошибке вызова.
     */
    @Override
    default String display() {
        return "def " + name();
    }
}
