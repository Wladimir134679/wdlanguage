package ru.wds.wdl.value;

/**
 * Потоки, заведённые скриптом: то, через что библиотека их создаёт.
 * <p>
 * <b>Заводить {@code new Thread} мимо этого интерфейса нельзя.</b> Причина не в стиле:
 * запуск обязан уметь закрыться, а закрыться — значит остановить то, что он породил.
 * Поток, о котором запуск не знает, переживает {@code close()}, просыпается и зовёт
 * функцию скрипта по уже закрытым модулям. Ровно это делали колбэки сокета до появления
 * реестра.
 * <p>
 * Интерфейс объявлен здесь, рядом с {@link CallContext}, по той же причине, по которой
 * там объявлен он сам: значения не должны зависеть от того, кто их выполняет. Реализацию
 * даёт запуск ({@code runtime}), а у вызывающего без запуска остаётся {@link #unmanaged()}.
 *
 * <h2>Размер стека задаётся явно</h2>
 * И это не тонкая настройка. Предел вложенности вызовов в языке — свойство движка
 * ({@code ExecutionContext.MAX_CALL_DEPTH}), а сколько кадров влезет — свойство потока,
 * который движку не подчиняется: в потоке с коротким стеком рекурсия упрётся
 * в {@code StackOverflowError} задолго до своего предела, и вместо ошибки скрипта
 * с местом в исходнике автор получит остановку без объяснений. Поэтому поток скрипта
 * создаётся со стеком {@link #STACK_SIZE}, а не с тем, что достанется.
 */
@FunctionalInterface
public interface ScriptThreads {

    /**
     * Стек потока скрипта.
     * <p>
     * Считается от предела вложенности: один вызов wdl стоит около десятка кадров Java,
     * предел — 256 вызовов, плюс кадры библиотек по дороге. Двух мегабайт хватает
     * с запасом, а платит за них только тот, кто и правда завёл поток.
     */
    long STACK_SIZE = 2L * 1024 * 1024;

    /**
     * Заводит и запускает поток скрипта.
     * <p>
     * Поток уже <b>запущен</b>, когда метод вернул управление: отдавать наружу
     * незапущенный поток значило бы разрешить менять его свойства (имя, признак
     * демона) в промежутке — а половина из них после старта уже не меняется,
     * и получилось бы два разных набора правил в зависимости от момента.
     *
     * @param name имя потока — оно же попадёт в диагностику; {@code null} — придумать
     * @param body тело; его ошибки ловит вызывающий, а не реестр
     * @return запущенный поток
     */
    Thread start(String name, Runnable body);

    /**
     * Реестра нет: поток просто создаётся и запускается.
     * <p>
     * Значение по умолчанию для вызывающего без запуска — тест, собирающий вывод
     * в строку, или приложение, зовущее функцию со своим {@link CallContext}.
     * Останавливать такие потоки некому, поэтому они демоны: висящий процесс —
     * худший исход из возможных.
     */
    static ScriptThreads unmanaged() {
        return (name, body) -> {
            Thread thread = new Thread(null, body, name == null ? "wdl-thread" : name, STACK_SIZE);
            thread.setDaemon(true);
            thread.start();
            return thread;
        };
    }
}
