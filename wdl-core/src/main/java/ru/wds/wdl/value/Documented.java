package ru.wds.wdl.value;

/**
 * Значение, которое умеет рассказать о себе словами.
 * <p>
 * Единственное, чего нет в самом значении: имя, вид, сигнатуру и состав инструмент
 * спрашивает у значения напрямую, а фразу «читает файл целиком» взять неоткуда.
 * Поэтому она объявляется <b>там же, где имя</b>, — рядом с телом функции,
 * в построителе, — и никакого второго списка описаний рядом с первым списком имён
 * не заводится. Второй список умеет ровно одно: разойтись с первым.
 * <p>
 * Выполнению это ничего не стоит и ничего не меняет: описание — поле, которое читает
 * только редактор. Значение, которому нечего сказать, интерфейс не реализует, и это
 * обычное дело, а не пробел.
 *
 * @see ru.wds.wdl.runtime.BuiltinFunction
 */
public interface Documented {

    /** Одна-две фразы для подсказки или {@code null}. */
    String documentation();

    /**
     * Описание того, что лежит <b>внутри</b>: метода класса, имени модуля.
     * <p>
     * Второй вопрос, а не второй интерфейс, потому что отвечает на него тот же
     * объект и знает он это из того же построителя: класс — про свои методы, модуль —
     * про свои имена. Значение-обёртка над чужим объектом описания своих членов
     * не имеет, и {@code null} здесь — обычный ответ.
     */
    default String documentation(String member) {
        return null;
    }

    default boolean hasDocumentation() {
        String text = documentation();
        return text != null && !text.isBlank();
    }
}
