package ru.wds.wdl.value;

import ru.wds.wdl.value.types.*;

/**
 * Значение времени выполнения.
 * <p>
 * Иерархия {@code sealed}: полный список типов известен компилятору, поэтому
 * любой {@code switch} по значению проверяется на полноту, а добавление нового
 * типа сразу подсвечивает все места, где его забыли учесть. В прошлой реализации
 * тип значения был {@code int}-константой — ошибиться было нечем, а компилятор
 * не помогал совсем.
 * <p>
 * Значения простых типов неизменяемы, {@link ArrayValue} и {@link MapValue} —
 * изменяемы и сравниваются по ссылке.
 * <p>
 * Тип {@code object} представлен двумя классами: {@link MapValue} — карта пар,
 * {@link InstanceObjectValue} — экземпляр класса, её наследник. Для языка это
 * один тип: {@code typeof} у обоих даёт {@code object}, и все операции над объектом
 * работают с обоими.
 * <p>
 * {@link FunctionValue}, {@link ClassValue} и {@link TraitValue} — {@code non-sealed}:
 * это единственные ветки, у которых реализация лежит в {@code runtime}, потому что
 * тянет за собой дерево и область видимости. Список типов от этого не открывается —
 * {@link ValueType} по-прежнему закрытый.
 * <p>
 * {@link ModuleValue} стоит отдельно от {@link MapValue}, хотя устроен похоже:
 * набор имён модуля задан его файлом, и обращаться с ним как со словарём — дописывать
 * ключи, спрашивать несуществующее и получать {@code null} — значит терять ошибки,
 * которые язык умеет назвать сразу.
 */
public sealed interface Value
        permits NullValue, BoolValue, NumberValue, StringValue, ArrayValue, MapValue,
                ModuleValue, FunctionValue, ClassValue, TraitValue {

    ValueType type();

    /**
     * Истинность значения в условиях и логических операциях.
     * <p>
     * Правило одно и на всё: ложны только {@code null} и {@code false}. Ноль,
     * пустая строка и пустой массив — истинны. Это правило легче держать в голове,
     * чем список исключений, и оно не даёт спутать «значения нет» с «значение равно нулю».
     */
    default boolean isTruthy() {
        return true;
    }

    /**
     * Представление для человека: то, что увидит {@code println} и что попадёт
     * в конкатенацию строк. Без кавычек вокруг строк — в отличие от {@link #toString()},
     * который остаётся отладочным видом.
     */
    String display();
}
