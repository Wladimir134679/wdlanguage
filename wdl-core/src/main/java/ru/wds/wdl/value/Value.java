package ru.wds.wdl.value;

import ru.wds.wdl.value.types.*;

/**
 * Значение времени выполнения.
 * <p>
 * Иерархия {@code sealed}: полный список типов известен компилятору, поэтому
 * любой {@code switch} по значению проверяется на полноту, а добавление нового
 * типа сразу подсвечивает все места, где его забыли учесть. В прошлой реализации
 * тип значения был {@code int}-константой — ошибиться было нечем, а компилятор
 * не помогал совсем.
 * <p>
 * Значения простых типов неизменяемы, {@link ArrayValue} и {@link ObjectValue} —
 * изменяемы и сравниваются по ссылке.
 */
public sealed interface Value
        permits NullValue, BoolValue, NumberValue, StringValue, ArrayValue, ObjectValue, FunctionValue {

    ValueType type();

    /**
     * Истинность значения в условиях и логических операциях.
     * <p>
     * Правило одно и на всё: ложны только {@code null} и {@code false}. Ноль,
     * пустая строка и пустой массив — истинны. Это правило легче держать в голове,
     * чем список исключений, и оно не даёт спутать «значения нет» с «значение равно нулю».
     */
    default boolean isTruthy() {
        return true;
    }

    /**
     * Представление для человека: то, что увидит {@code println} и что попадёт
     * в конкатенацию строк. Без кавычек вокруг строк — в отличие от {@link #toString()},
     * который остаётся отладочным видом.
     */
    String display();
}
