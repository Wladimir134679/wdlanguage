package ru.wds.wdl.value;

import ru.wds.wdl.source.Span;
import ru.wds.wdl.value.types.InstanceObjectValue;
import ru.wds.wdl.value.types.MapValue;

import java.util.List;

/**
 * Класс как значение.
 * <p>
 * Класс лежит в обычной переменной обычной области видимости — его можно передать
 * аргументом, положить в массив и в поле объекта. Отсюда и {@code new} говорит
 * не «здесь имя класса», а «создай экземпляр того, что получится слева»:
 * {@code new kinds[0](1, 2)} законен ровно потому, что класс — значение.
 * <p>
 * <b>Реализаций две, и интерпретатор их не различает.</b> Класс, написанный
 * на wdl ({@code runtime.WdlClass}), знает про форму, замыкание и дерево тела;
 * класс, встроенный приложением ({@code bridge.NativeClass}), — про Java-лямбды.
 * Всё, что нужно вычислению выражения, собрано здесь: создать экземпляр, найти
 * метод, прочитать поле самого класса и ответить оператору {@code is}. Тот же приём,
 * что у {@link FunctionValue}: интерфейс здесь, реализации там, где им место.
 * <p>
 * Экземпляр класса — <b>не</b> отдельный тип значения: это
 * {@link InstanceObjectValue} со ссылкой на класс, поэтому {@code typeof(p)} даёт
 * {@code object}, а {@code len}, перебор и обращение по ключу работают
 * у экземпляра сами собой.
 */
public non-sealed interface ClassValue extends Value {

    String name();

    /** Сколько аргументов принимает {@code new} — по заголовку класса. */
    Arity arity();

    /**
     * Контракт создания: имена параметров заголовка и их обязательность.
     * <p>
     * То же правило, что у {@link FunctionValue#signature()}: по умолчанию имён нет
     * и {@code new} остаётся позиционным. Класс на wdl берёт имена из заголовка,
     * встроенный — из объявленных полей.
     */
    default Signature signature() {
        return Signature.positional(arity());
    }

    /**
     * Создаёт экземпляр.
     * <p>
     * Число аргументов проверено вызывающим по {@link #arity()} — до входа сюда,
     * чтобы сообщение было одинаковым для всех классов, а сам класс начинался
     * с дела, а не с проверок. Ровно то же правило, что у функции.
     */
    Value instantiate(List<Value> arguments, CallContext context, Span span);

    /**
     * Создаёт экземпляр по разложенным аргументам.
     * <p>
     * Переопределяется по той же причине и теми же, что и
     * {@link FunctionValue#call(CallContext, Arguments, Span)}: пропуск в середине
     * доживает сюда только у класса с отложенными значениями по умолчанию, то есть
     * у класса, написанного на wdl.
     */
    default Value instantiate(Arguments arguments, CallContext context, Span span) {
        return instantiate(arguments.asList(), context, span);
    }

    /**
     * Метод, связанный с этим экземпляром, или {@code null}, если такого метода нет.
     * <p>
     * Связанный метод — обычное значение-функция: его можно прочитать в переменную
     * и вызвать позже, объект при этом не потеряется. Отдельного «вызова метода»
     * в языке нет.
     */
    FunctionValue method(InstanceObjectValue instance, String name);

    /**
     * Свойство с этим именем или {@code null}, если его нет.
     * <p>
     * Спрашивается у класса, а не у экземпляра: за именем стоит код, а код принадлежит
     * классу — ровно как метод. Экземпляр появляется в момент чтения и приходит
     * аргументом в {@link Property#read}.
     * <p>
     * Реализация по умолчанию — «свойств нет»: класс, встроенный приложением, вправе
     * не знать о них вовсе, и заставлять его писать {@code return null} незачем.
     */
    default Property property(String name) {
        return null;
    }

    /**
     * Родитель или {@code null}, если класс ничему не наследует.
     * <p>
     * Заведено ради интроспекции из скрипта ({@code Circle.parent}) — и отдаёт
     * <b>значение</b>, а не имя: по имени нельзя ни спросить {@code is}, ни создать
     * экземпляр, а реестра имён в языке нет. По умолчанию родителя нет: класс,
     * встроенный приложением, вправе о наследовании не знать вовсе.
     */
    default ClassValue parentClass() {
        return null;
    }

    /** Подмешанные трейты — тоже значениями и по той же причине, что родитель. */
    default List<TraitValue> traits() {
        return List.of();
    }

    /**
     * Имена методов — все, включая доставшиеся от родителя и из трейтов.
     * <p>
     * Плоская таблица у класса уже собрана при объявлении, поэтому это не обход
     * иерархии, а её ключи. Порядок — тот, в котором таблица собиралась.
     */
    default List<String> methodNames() {
        return List.of();
    }

    /**
     * Имена полей экземпляра в том порядке, в каком их задаёт заголовок класса.
     * <p>
     * <b>Порядок здесь — договорённость, а не деталь.</b> На нём держится распаковка
     * по позициям ({@code x, y, z = *point}): заголовок класса и есть список его
     * компонентов, ровно как у Java-рекорда, и другого источника порядка у экземпляра
     * нет — порядок пар в самом объекте это порядок вставки, куда попадает и всё,
     * что завёл конструктор через {@code this}.
     * <p>
     * Пустой список по умолчанию значит «класс о полях не рассказывает»: распаковка
     * такого экземпляра по позициям не удастся, и это честнее, чем разложить его
     * по случайному порядку. Наследуемые поля входят наравне со своими — таблица
     * у класса уже плоская, и распаковке важно, что у экземпляра есть, а не откуда.
     */
    default List<String> fieldNames() {
        return List.of();
    }

    /** Имена свойств — тем же правилом, что и методы. */
    default List<String> propertyNames() {
        return List.of();
    }

    /**
     * Ключ этого класса в таблице членов запуска.
     * <p>
     * Ключ — <b>идентичность значения</b>, а не имя: два класса {@code Point} из разных
     * модулей расширяются независимо, и общее имя их не роднит. Переопределяет это
     * только дескриптор типа: у него ключ — сам тип, потому что {@code extend Array}
     * добавляет член всем массивам, а не одному значению-дескриптору.
     */
    default Object memberKey() {
        return this;
    }

    /**
     * Поля самого класса: «статика» и фабрики.
     * <p>
     * Отдельного слова {@code static} нет и не нужно — класс это значение, значение
     * это контейнер, запись по ключу уже работает. Поэтому здесь обычная карта,
     * и {@code Point.zero = new Point(0, 0)} — обычная запись в неё.
     */
    MapValue statics();

    /**
     * Ответ оператора {@code is}: этот ли класс, его предок или подмешанный трейт.
     * <p>
     * Спрашивается у класса, а не вычисляется на месте, потому что ответ
     * заготовлен при объявлении: цепочка предков и набор трейтов известны
     * тогда же, когда собираются плоские таблицы.
     */
    boolean conformsTo(Value classOrTrait);

    /**
     * Отвечает на {@code значение is этот}: то же самое, что стоит слева от {@code is}.
     * <p>
     * <b>Решение — здесь, а не в {@code runtime.Operations}.</b> Оператор {@code is}
     * спрашивает не «что слева», а «что справа»: правый операнд знает, как отвечать
     * на вопрос о принадлежности, а левый — нет. Будь ответ зашит в {@code Operations},
     * там жила бы проверка {@code instanceof ClassValue} с решением внутри — и вторая
     * такая же для {@link TraitValue}, и обеим сторонам понадобился бы способ
     * различить чужую реализацию {@code ClassValue}, которую написало приложение.
     * Здесь же вопрос закрывается методом интерфейса: своя реализация отвечает
     * по-своему, не трогая ни оператор, ни чужой код.
     * <p>
     * Реализация по умолчанию — дословно то, что оператор делал до появления
     * дескрипторов типов: значение принадлежит классу, если это экземпляр и его
     * класс {@linkplain #conformsTo(Value) конформен} этому. {@code TypeValue}
     * (дескриптор {@code Number}, {@code Object}, …) отвечает иначе — сравнением
     * {@link Value#type()}, — и поэтому переопределяет этот метод целиком.
     */
    default boolean matches(Value value) {
        return value instanceof InstanceObjectValue instance && instance.owner().conformsTo(this);
    }

    /**
     * Можно ли писать в {@link #statics()} снаружи: {@code Point.zero = ...}.
     * <p>
     * По умолчанию {@code true} — класс, написанный на wdl или встроенный
     * приложением, для того и заводит «статику», чтобы в неё писали. У дескриптора
     * типа ({@code runtime.TypeValue}) ответ обратный: он один на процесс, и запись
     * в него была бы состоянием, которое переживает свой запуск и видно чужому
     * скрипту в соседнем интерпретаторе, — поэтому он единственный, кто
     * переопределяет этот метод в {@code false}.
     */
    default boolean staticsWritable() {
        return true;
    }

    @Override
    default ValueType type() {
        return ValueType.CLASS;
    }
}
