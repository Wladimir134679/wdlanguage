package ru.wds.wdl.value;

/**
 * Класс как значение.
 * <p>
 * Класс лежит в обычной переменной обычной области видимости — его можно передать
 * аргументом, положить в массив и в поле объекта. Отсюда и {@code new} говорит
 * не «здесь имя класса», а «создай экземпляр того, что получится слева»:
 * {@code new kinds[0](1, 2)} законен ровно потому, что класс — значение.
 * <p>
 * Здесь только то, что нужно вычислению выражения: имя для сообщений, число
 * аргументов создания и ответ на вопрос оператора {@code is}. Всё остальное —
 * плоские таблицы полей и методов, замыкание, конструктор — живёт в реализации
 * ({@code ru.wds.wdl.runtime.WdlClass}), потому что тянет за собой и дерево,
 * и область видимости, а пакету {@code value} до них дела нет. Тот же приём,
 * что у {@link FunctionValue}: интерфейс здесь, реализация в {@code runtime}.
 * <p>
 * Экземпляр класса — <b>не</b> отдельный тип значения: это
 * {@link ru.wds.wdl.value.types.InstanceObjectValue} со ссылкой на класс, поэтому
 * {@code typeof(p)} даёт {@code object}, а {@code len}, перебор и обращение
 * по ключу работают у экземпляра сами собой.
 */
public non-sealed interface ClassValue extends Value {

    String name();

    /** Сколько аргументов принимает {@code new} — по заголовку класса. */
    Arity arity();

    /**
     * Ответ оператора {@code is}: этот ли класс, его предок или подмешанный типаж.
     * <p>
     * Спрашивается у класса, а не вычисляется на месте, потому что ответ
     * заготовлен при объявлении: цепочка предков и набор типажей известны
     * тогда же, когда собираются плоские таблицы.
     */
    boolean conformsTo(Value classOrTrait);

    @Override
    default ValueType type() {
        return ValueType.CLASS;
    }
}
