package ru.wds.wdl.diagnostic;

/**
 * Вид проблемы — то же сообщение, но машиночитаемо.
 * <p>
 * Текст сообщения пишется для человека и меняется свободно: его правят, уточняют,
 * дополняют советом. Редактору же нужно устойчивое имя проблемы — по нему он гасит
 * отдельную проверку, вешает быструю правку, настраивает строгость и ссылается
 * на объяснение. Сравнивать ради этого строки нельзя: первая же правка формулировки
 * сломала бы всё разом.
 * <p>
 * <b>Код есть не у всех сообщений, и это нормально.</b> {@link #NONE} — значение
 * по умолчанию: сообщение без кода ведёт себя ровно так, как вело до появления
 * этого перечисления. Коды добавляются по мере того, как у проблемы появляется
 * потребитель — быстрая правка или настройка; заводить полторы сотни имён вперёд
 * означало бы придумать имена тому, чем никто не пользуется.
 */
public enum DiagnosticCode {

    /** Кода нет: сообщение различается только текстом. */
    NONE,

    /** Символ, которого в языке не существует. */
    UNKNOWN_CHARACTER,

    /** Строковый литерал не закрыт кавычкой до конца строки. */
    UNCLOSED_STRING,

    /** Блочный комментарий не закрыт: остаток файла съеден. */
    UNCLOSED_COMMENT,

    /** На этом месте ожидался определённый токен, а нашёлся другой. */
    EXPECTED_TOKEN,

    /** На этом месте ожидалось выражение. */
    EXPECTED_EXPRESSION
}
