package ru.wds.wdl.diagnostic;

/**
 * Согласование существительного с числом: «1 значение», «2 значения», «5 значений».
 * <p>
 * Живёт рядом с диагностикой, а не там, где считают, по той же причине, по которой
 * {@code Arity.describeArguments()} собирает свою фразу целиком: склеенное из «2» и
 * «значений» сообщение читается как машинный перевод, а разводить три формы по месту
 * употребления — значит переписывать одно и то же правило в каждом сообщении.
 * <p>
 * Правило русского счётного согласования одно на все слова, поэтому здесь оно
 * и записано один раз, а формы слова приходят аргументами.
 */
public final class Plural {

    private Plural() {
    }

    /**
     * Число со словом в согласованной форме: {@code of(2, "значение", "значения",
     * "значений")} даёт {@code "2 значения"}.
     *
     * @param one  форма при 1, 21, 31 — «значение»
     * @param few  форма при 2–4, 22–24 — «значения»
     * @param many форма при 0, 5–20 — «значений»
     */
    public static String of(int count, String one, String few, String many) {
        return count + " " + word(count, one, few, many);
    }

    /** Та же форма слова, но без самого числа — когда число уже стоит рядом. */
    public static String word(int count, String one, String few, String many) {
        // Одиннадцать-четырнадцать — исключение из правила по последней цифре:
        // «11 значений», а не «11 значение».
        int tens = Math.abs(count) % 100;
        if (tens >= 11 && tens <= 14) {
            return many;
        }
        return switch (Math.abs(count) % 10) {
            case 1 -> one;
            case 2, 3, 4 -> few;
            default -> many;
        };
    }

    /** «1 значение», «2 значения», «5 значений» — самая частая пара в распаковке. */
    public static String values(int count) {
        return of(count, "значение", "значения", "значений");
    }

    /** «1 имя», «2 имени», «5 имён». */
    public static String names(int count) {
        return of(count, "имя", "имени", "имён");
    }
}
