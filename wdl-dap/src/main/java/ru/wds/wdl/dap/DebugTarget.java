package ru.wds.wdl.dap;

import ru.wds.wdl.debug.DebugSession;

/**
 * Что отлаживают: свой запуск или чужой.
 * <p>
 * Различие ровно одно, и оно про право: <b>своё можно остановить, чужое — нельзя</b>.
 * Запуск, заведённый адаптером по просьбе {@code launch}, ему и принадлежит: кнопка
 * «Стоп» в редакторе обязана его прекратить. Запуск живого приложения, к которому
 * подключились ({@code attach}), адаптеру не принадлежит вовсе — отключение отладчика
 * не должно ронять сервер, игру или мод, в котором скрипт живёт. Всё остальное —
 * точки, шаги, кадры, вычисления — у обоих одинаково, потому что этим занимается
 * сессия, а она одна и та же.
 */
interface DebugTarget extends AutoCloseable {

    /** Сессия отладки этого запуска. */
    DebugSession session();

    /**
     * Пускает скрипт: у {@code launch} — выполняет файл, у {@code attach} — ничего,
     * потому что скрипт уже считает.
     * <p>
     * Зовётся из {@code configurationDone}, а не из {@code launch}: до этой минуты
     * клиент расставляет точки останова, и запустить скрипт раньше значило бы
     * проскочить их все.
     */
    void start();

    /**
     * Прекращает выполнение, если оно наше.
     * <p>
     * Чужой запуск не трогается: отладчик здесь зритель.
     */
    void terminate();

    /** Отпускает отладку; своё закрывает, чужое оставляет работать. */
    @Override
    void close();
}
